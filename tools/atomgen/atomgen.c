/*
 * atomgen: reads atoms.txt (one name per line, '#' starts a comment) and writes the static atom
 * table src/dom/atoms.inc. Atom ids follow line order starting at 1. A name listed twice is
 * skipped. Each name becomes the enumerator EMBI_ATOM_<name>, with every byte outside
 * [A-Za-z0-9_] replaced by '_'. Two different names that map to the same enumerator are an error.
 *
 * It also writes the plain name list (one quoted string per line, id order, no entry for id 0) to
 * src/base/static_atoms.inc, which base interns first so the ids hold in any init order.
 *
 * Usage: atomgen <atoms.txt> <atoms.inc> <static_atoms.inc>
 */
#include <stdbool.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#define MAX_LINE 512

typedef struct entry {
    char *name;
    char *ident;
} entry;

typedef struct table {
    entry *items;
    size_t len;
    size_t cap;
} table;

[[noreturn]] static void fail(const char *msg, const char *arg)
{
    fprintf(stderr, "atomgen: %s%s%s\n", msg, arg ? ": " : "", arg ? arg : "");
    exit(1);
}

static char *dup_str(const char *p, size_t n)
{
    char *s = malloc(n + 1);
    if (!s) {
        fail("out of memory", nullptr);
    }
    memcpy(s, p, n);
    s[n] = '\0';
    return s;
}

static bool is_name_char(unsigned char c)
{
    return (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || (c >= '0' && c <= '9') ||
           c == '_' || c == '-' || c == ':';
}

static char *make_ident(const char *name)
{
    size_t n = strlen(name);
    char *s = malloc(n + 11);
    if (!s) {
        fail("out of memory", nullptr);
    }
    memcpy(s, "EMBI_ATOM_", 10);
    for (size_t i = 0; i < n; i++) {
        unsigned char c = (unsigned char)name[i];
        bool keep = (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || (c >= '0' && c <= '9') ||
                    c == '_';
        s[10 + i] = keep ? (char)c : '_';
    }
    s[10 + n] = '\0';
    return s;
}

static bool has_name(const table *t, const char *name)
{
    for (size_t i = 0; i < t->len; i++) {
        if (strcmp(t->items[i].name, name) == 0) {
            return true;
        }
    }
    return false;
}

static void add(table *t, const char *name)
{
    if (has_name(t, name)) {
        return;
    }
    char *ident = make_ident(name);
    for (size_t i = 0; i < t->len; i++) {
        if (strcmp(t->items[i].ident, ident) == 0) {
            char msg[512];
            snprintf(msg, sizeof msg, "names '%s' and '%s' map to the same identifier",
                     t->items[i].name, name);
            fail(msg, nullptr);
        }
    }
    if (t->len == t->cap) {
        size_t ncap = t->cap ? t->cap * 2 : 256;
        entry *grown = realloc(t->items, ncap * sizeof *t->items);
        if (!grown) {
            fail("out of memory", nullptr);
        }
        t->items = grown;
        t->cap = ncap;
    }
    t->items[t->len].name = dup_str(name, strlen(name));
    t->items[t->len].ident = ident;
    t->len++;
}

static void parse(table *t, const char *path)
{
    FILE *f = fopen(path, "rb");
    if (!f) {
        fail("cannot open input", path);
    }
    char line[MAX_LINE];
    size_t lineno = 0;
    while (fgets(line, sizeof line, f)) {
        lineno++;
        size_t n = strlen(line);
        if (n == MAX_LINE - 1 && line[n - 1] != '\n') {
            fail("line too long in", path);
        }
        size_t b = 0;
        size_t e = n;
        while (e > 0 && (line[e - 1] == '\n' || line[e - 1] == '\r' || line[e - 1] == ' ' ||
                         line[e - 1] == '\t')) {
            e--;
        }
        while (b < e && (line[b] == ' ' || line[b] == '\t')) {
            b++;
        }
        if (b == e || line[b] == '#') {
            continue;
        }
        for (size_t i = b; i < e; i++) {
            if (!is_name_char((unsigned char)line[i])) {
                char msg[256];
                snprintf(msg, sizeof msg, "%s:%zu: invalid character in name", path, lineno);
                fail(msg, nullptr);
            }
        }
        char *name = dup_str(line + b, e - b);
        add(t, name);
        free(name);
    }
    fclose(f);
}

static void emit(const table *t, const char *path)
{
    FILE *f = fopen(path, "wb");
    if (!f) {
        fail("cannot open output", path);
    }
    fprintf(f, "/* Generated by tools/atomgen from tools/atomgen/atoms.txt. Do not edit. */\n");
    fprintf(f, "/* Ids follow line order starting at 1. Including this file declares the enum;\n");
    fprintf(f, " * the name table is emitted only when EMBI_DOM_ATOM_TABLE is defined (atoms.c). */\n");
    fprintf(f, "enum {\n");
    for (size_t i = 0; i < t->len; i++) {
        fprintf(f, "    %s = %zu,\n", t->items[i].ident, i + 1);
    }
    fprintf(f, "    EMBI_ATOM_STATIC_COUNT = %zu\n", t->len + 1);
    fprintf(f, "};\n\n");
    fprintf(f, "#ifdef EMBI_DOM_ATOM_TABLE\n");
    fprintf(f, "static const char *const embi_dom_atom_names[EMBI_ATOM_STATIC_COUNT] = {\n");
    fprintf(f, "    \"\",\n");
    for (size_t i = 0; i < t->len; i++) {
        fprintf(f, "    \"%s\",\n", t->items[i].name);
    }
    fprintf(f, "};\n");
    fprintf(f, "#endif\n");
    if (fclose(f) != 0) {
        fail("write failed", path);
    }
}

static void emit_names(const table *t, const char *path)
{
    FILE *f = fopen(path, "wb");
    if (!f) {
        fail("cannot open output", path);
    }
    fprintf(f, "/* Generated by tools/atomgen from tools/atomgen/atoms.txt. Do not edit. */\n");
    fprintf(f, "/* Static atom names in id order; the first entry is atom id 1. */\n");
    for (size_t i = 0; i < t->len; i++) {
        fprintf(f, "\"%s\",\n", t->items[i].name);
    }
    if (fclose(f) != 0) {
        fail("write failed", path);
    }
}

int main(int argc, char **argv)
{
    if (argc != 4) {
        fprintf(stderr, "usage: atomgen <atoms.txt> <atoms.inc> <static_atoms.inc>\n");
        return 2;
    }
    table t = {nullptr, 0, 0};
    parse(&t, argv[1]);
    emit(&t, argv[2]);
    emit_names(&t, argv[3]);
    fprintf(stderr, "atomgen: wrote %zu atoms to %s\n", t.len, argv[2]);
    return 0;
}
