#!/usr/bin/env python3
"""Writes src/layout/charclass_data.inc: the compact ranges of the General_Category classes that ::first-letter needs
(Ps Pe Pi Pf Po; Mn Mc Me), decoded from the generated JS tables (src/js/regexp_unicode.inc). Run from the source root."""
import re, sys
src = open('src/js/regexp_unicode.inc', encoding='utf-8').read()
off = [int(x) for x in re.search(r'embi_re_set_off\[[^\]]*\]\s*=\s*\{([^}]*)\}', src, re.S).group(1).replace('\n', ' ').split(',') if x.strip()]
data = bytes(int(x, 0) for x in re.search(r'embi_re_set_data\[[^\]]*\]\s*=\s*\{([^}]*)\}', src, re.S).group(1).replace('\n', ' ').split(',') if x.strip())

def varint(p):
    v = s = 0
    while True:
        b = data[p]; p += 1
        v |= (b & 0x7f) << s; s += 7
        if not b & 0x80 or s >= 35: return v, p

def ranges(i):
    p = off[i]
    n, p = varint(p)
    prev = 0; out = []
    for _ in range(n):
        d, p = varint(p); lo = prev + d
        w, p = varint(p); hi = lo + w
        out.append((lo, hi)); prev = hi + 1
    return out

def merge(ids):
    rs = sorted(r for i in ids for r in ranges(i))
    out = []
    for lo, hi in rs:
        if out and lo <= out[-1][1] + 1: out[-1] = (out[-1][0], max(out[-1][1], hi))
        else: out.append((lo, hi))
    return out

def has(rs, cp):
    return any(lo <= cp <= hi for lo, hi in rs)

# The set indices come from the order of src/js/regexp_unicode.inc; verify them with known code points so a reordered
# JS table fails here instead of regenerating a wrong layout table.
_P = merge([13, 14, 15, 16, 17])
_M = merge([5, 6, 7])
for cp, what in ((0x00AB, 'Pi'), (0x00BB, 'Pf'), (0x00A1, 'Po'), (0x0F3A, 'Ps'), (0x0F3B, 'Pe'), (0x201C, 'Pi'), (0x3002, 'Po')):
    assert has(_P, cp), 'U+%04X (%s) is missing from the punctuation sets: the set indices in %s changed' % (cp, what, 'regexp_unicode.inc')
for cp in (0x0041, 0x0030, 0x0024, 0x002B):
    assert not has(_P, cp), 'U+%04X must not be in the punctuation sets' % cp
for cp in (0x0300, 0x0903, 0x20DD, 0x0E31):
    assert has(_M, cp), 'U+%04X is missing from the mark sets' % cp
assert not has(_M, 0x0041) and not has(_M, 0x00AB), 'letters or punctuation in the mark sets'

def emit(name, rs):
    s = 'static const uint32_t %s[][2] = {\n' % name
    line = '   '
    for lo, hi in rs:
        item = ' {0x%X, 0x%X},' % (lo, hi)
        if len(line) + len(item) > 118: s += line + '\n'; line = '   '
        line += item
    return s + line + '\n};\n'

with open('src/layout/charclass_data.inc', 'w') as f:
    f.write('/* Generated by tools/layoutgen/charclass.py from the UCD 17 tables of the JS regexp engine. Do not edit. */\n')
    f.write(emit('k_fl_punct', [r for r in merge([13, 14, 15, 16, 17]) if r[1] >= 0x80]))
    f.write(emit('k_marks', [r for r in merge([5, 6, 7]) if r[1] >= 0x300]))
