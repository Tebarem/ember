/*
 * entitiesgen: writes the named character reference table used by the HTML tokenizer.
 *
 *     entitiesgen <entities.json> <out.inc>
 *
 * Input is the WHATWG entities.json (keys such as "&AElig;" and "&AElig", each with a
 * "codepoints" array of one or two code points). Output rows are sorted by name bytes, which the
 * tokenizer relies on for its prefix search. Names keep their trailing ';' when they have one.
 */

#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include "json_mini.h"

typedef struct entry {
    char *name; /* without the leading '&' */
    size_t len;
    uint32_t cp[2];
    size_t ncp;
} entry;

static int entry_cmp(const void *a, const void *b)
{
    return strcmp(((const entry *)a)->name, ((const entry *)b)->name);
}

static int fail(const char *msg, const char *what)
{
    fprintf(stderr, "entitiesgen: %s: %s\n", msg, what);
    return 1;
}

static bool valid_name_char(unsigned char c)
{
    return (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || (c >= '0' && c <= '9') || c == ';';
}

int main(int argc, char **argv)
{
    if (argc != 3) {
        fprintf(stderr, "usage: entitiesgen <entities.json> <out.inc>\n");
        return 2;
    }

    FILE *in = fopen(argv[1], "rb");
    if (in == nullptr) {
        return fail("cannot open input", argv[1]);
    }
    if (fseek(in, 0, SEEK_END) != 0) {
        fclose(in);
        return fail("cannot seek input", argv[1]);
    }
    long size = ftell(in);
    rewind(in);
    if (size <= 0) {
        fclose(in);
        return fail("empty input", argv[1]);
    }
    char *text = malloc((size_t)size);
    if (text == nullptr || fread(text, 1, (size_t)size, in) != (size_t)size) {
        fclose(in);
        return fail("cannot read input", argv[1]);
    }
    fclose(in);

    jm_val root;
    if (!jm_parse(text, (size_t)size, &root) || root.type != JM_OBJECT) {
        return fail("input is not a JSON object", argv[1]);
    }
    free(text);

    entry *entries = calloc(root.count ? root.count : 1, sizeof *entries);
    if (entries == nullptr) {
        return fail("out of memory", "entries");
    }
    size_t n = 0;
    for (size_t i = 0; i < root.count; i++) {
        const char *key = root.keys[i];
        if (key[0] != '&') {
            continue;
        }
        const char *name = key + 1;
        size_t len = strlen(name);
        if (len == 0 || len > 40) {
            return fail("entity name length out of range", key);
        }
        for (size_t k = 0; k < len; k++) {
            if (!valid_name_char((unsigned char)name[k])) {
                return fail("entity name has an unexpected character", key);
            }
        }
        const jm_val *cps = jm_get(&root.items[i], "codepoints");
        if (cps == nullptr || cps->type != JM_ARRAY || cps->count < 1 || cps->count > 2) {
            return fail("entity needs one or two codepoints", key);
        }
        entry *e = &entries[n++];
        e->name = malloc(len + 1);
        if (e->name == nullptr) {
            return fail("out of memory", "name");
        }
        memcpy(e->name, name, len + 1);
        e->len = len;
        e->ncp = cps->count;
        for (size_t k = 0; k < cps->count; k++) {
            const jm_val *v = &cps->items[k];
            if (v->type != JM_NUMBER || v->num < 1 || v->num > 0x10FFFF) {
                return fail("bad code point", key);
            }
            e->cp[k] = (uint32_t)v->num;
        }
    }

    qsort(entries, n, sizeof *entries, entry_cmp);
    for (size_t i = 1; i < n; i++) {
        if (strcmp(entries[i - 1].name, entries[i].name) == 0) {
            return fail("duplicate entity name", entries[i].name);
        }
    }

    FILE *out = fopen(argv[2], "wb");
    if (out == nullptr) {
        return fail("cannot open output", argv[2]);
    }
    /* SZ3a: the names are one string pool without separators and the rows hold 16-bit offsets into it; the second code
     * point is an index into a table of the few distinct values (index 0: none). 8 bytes a row instead of 24 and no
     * relocations. */
    uint32_t cp2tab[256];
    size_t ncp2 = 0, pool = 0;
    for (size_t i = 0; i < n; i++) {
        const entry *e = &entries[i];
        pool += e->len;
        if (e->ncp > 1) {
            size_t k = 0;
            while (k < ncp2 && cp2tab[k] != e->cp[1]) {
                k++;
            }
            if (k == ncp2) {
                if (ncp2 == 255) {
                    return fail("too many second code points", e->name);
                }
                cp2tab[ncp2++] = e->cp[1];
            }
        }
    }
    if (pool > 65535) {
        return fail("name pool too large", "pool");
    }
    fprintf(out, "/* Generated by tools/entitiesgen from tools/entitiesgen/data/entities.json.\n");
    fprintf(out, " * Do not edit. Rows are sorted by name bytes; the tokenizer relies on that order.\n");
    fprintf(out, " * Row: {offset of the name (without '&') in ht_entity_names, length, index in ht_entity_cp2 of the second\n");
    fprintf(out, " * code point (0: none), first code point}. */\n");
    fprintf(out, "static const uint32_t ht_entity_cp2[%zu] = {0u", ncp2 + 1);
    for (size_t k = 0; k < ncp2; k++) {
        fprintf(out, ", %uu", (unsigned)cp2tab[k]);
    }
    fprintf(out, "};\n");
    fprintf(out, "static const char ht_entity_names[%zu] =", pool + 1);
    {
        size_t col = 0;
        for (size_t i = 0; i < n; i++) {
            if (col == 0 || col > 100) {
                fprintf(out, "%s\n    \"", i == 0 ? "" : "\"");
                col = 0;
            }
            fprintf(out, "%s", entries[i].name);
            col += entries[i].len;
        }
        fprintf(out, "\";\n");
    }
    fprintf(out, "static const ht_entity ht_entities[] = {\n");
    size_t off = 0;
    for (size_t i = 0; i < n; i++) {
        const entry *e = &entries[i];
        size_t k = 0;
        if (e->ncp > 1) {
            while (cp2tab[k] != e->cp[1]) {
                k++;
            }
            k++;
        }
        fprintf(out, "    {%zu, %zu, %zu, %uu},\n", off, e->len, k, (unsigned)e->cp[0]);
        off += e->len;
    }
    fprintf(out, "};\n");
    if (fclose(out) != 0) {
        return fail("cannot write output", argv[2]);
    }

    jm_free(&root);
    fprintf(stderr, "entitiesgen: wrote %zu entities to %s\n", n, argv[2]);
    return 0;
}
