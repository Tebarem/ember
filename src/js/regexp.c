/*
 * RegExp engine: ECMAScript pattern parser (ES2025 grammar, Annex B for non-u patterns), a
 * bytecode compiler, and a backtracking matcher with an explicit backtrack stack.
 *
 * Pipeline: prescan (group count, named groups) -> recursive-descent parser -> AST (arena) ->
 * code generation (one instruction array per program) -> matcher. Character classes are sorted
 * range lists; the i flag is applied by closing each class under canonicalization at compile
 * time, so matching only canonicalizes the input character (ECMA-262 CharacterSetMatcher).
 *
 * Unicode data comes from regexp_unicode.inc, generated by tools/unicodegen/propgen.c.
 */
