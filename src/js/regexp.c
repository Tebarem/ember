/* Copies a scratch set into the long-lived arena at its exact size. A set that is already shared
 * is referenced, not copied. in and out may be the same object. */
static void set_persist(re_parser *p, const re_set *in, re_set *out)
{
    if (in->shared) {
        *out = *in;
        return;
    }
    re_set res = {0};
    if (in->n) {
        res.r = embi_arena_alloc(p->ar, (size_t)in->n * sizeof *res.r, alignof(re_range));
        memcpy(res.r, in->r, (size_t)in->n * sizeof *res.r);
    }
    res.n = in->n;
    res.cap = in->n;
    res.nnorm = in->n;
    res.shared = true;
    *out = res;
}

/* Bytes in the long-lived arena. Only the tail block is ever bumped, so blocks before it are final
 * and are summed once; the cursor makes this O(1) amortized. */
static size_t parse_bytes(re_parser *p)
{
    embi_arena *a = p->ar;
    if (!a->last) {
        return 0;
    }
    if (!p->acct_blk) {
        p->acct_blk = a->first;
    }
    while (p->acct_blk != a->last) {
        p->acct_done += p->acct_blk->used;
        p->acct_blk = p->acct_blk->next;
    }
    return p->acct_done + a->last->used;
}

/* Fails the parse with "pattern too complex" once the AST outgrows its budget, instead of letting
 * a script-supplied pattern drive the process into allocation failure. Returns true when the parse
 * has failed or is over budget. */
static bool over_budget(re_parser *p)
{
    if (p->failed) {
        return true;
    }
    if (parse_bytes(p) > RE_PARSE_MAX_BYTES) {
        perr(p, "pattern too complex");
        return true;
    }
    return false;
}

static const re_set *ecache_get(const re_parser *p, uint64_t key)
{
    for (uint32_t i = 0; i < p->necache; i++) {
        if (p->ecache[i].key == key) {
            return &p->ecache[i].set;
        }
    }
    return nullptr;
}

static void ecache_put(re_parser *p, uint64_t key, const re_set *set)
{
    uint32_t slot;
    if (p->necache < RE_ECACHE) {
        slot = p->necache++;
    } else {
        slot = p->enext;
        p->enext = (p->enext + 1) % RE_ECACHE;
    }
    p->ecache[slot].key = key;
    p->ecache[slot].set = *set;
}

/* Cache key for an escape: what it is, whether it is negated, and the case mode it was built in. */
static uint64_t ecache_key(const re_parser *p, uint64_t what, bool neg)
{
    return (what << 3) | (neg ? 1u : 0u) | (p->icase ? 2u : 0u);
}

/* The set of all characters, shared and built once per parse and mode. */
static void universe(re_parser *p, re_set *out)
{
    uint32_t k = (p->v && p->icase) ? 1u : 0u;
    if (!p->uni_have[k]) {
        embi_arena_pos m = embi_arena_mark(&p->tmp);
        re_set all = {0};
        set_push(&p->tmp, &all, 0, p->uni ? 0x10FFFFu : 0xFFFFu);
        if (k) {
            re_set dom = {0};
            fold_domain(&p->tmp, &dom);
            re_set rest = {0};
            set_subtract(&p->tmp, &all, &dom, &rest);
            set_persist(p, &rest, &p->uni_cache[k]);
        } else {
            set_persist(p, &all, &p->uni_cache[k]);
        }
        embi_arena_reset_to(&p->tmp, m);
        p->uni_have[k] = true;
    }
    *out = p->uni_cache[k];
}

/* out = canonicalization image of 'in': every member replaced by its Canonicalize value. All
 * temporaries and the result live in the scratch arena (or are 'in' itself); the caller releases
 * them. */
static void canon_set(re_parser *p, const re_set *in, bool uni, re_set *out)
{
    const embi_re_casemap *map = uni ? embi_re_fold_u : embi_re_canon_nu;
    uint32_t mapn = uni ? EMBI_RE_NFOLD_U : EMBI_RE_NCANON_NU;
    re_set rem = {0};
    re_set add = {0};
    /* Cost is proportional to the overlap of the set with the table, not to the table size. */
    for (uint32_t k = 0; k < in->n; k++) {
        uint32_t lo = 0;
        uint32_t hi = mapn;
        while (lo < hi) { /* first entry with from >= in->r[k].lo */
            uint32_t mid = lo + (hi - lo) / 2;
            if (map[mid].from < in->r[k].lo) {
                lo = mid + 1;
            } else {
                hi = mid;
            }
        }
        for (uint32_t i = lo; i < mapn && map[i].from <= in->r[k].hi; i++) {
            set_push(&p->tmp, &rem, map[i].from, map[i].from);
            set_push(&p->tmp, &add, map[i].to, map[i].to);
        }
    }
    if (rem.n == 0) {
        *out = *in;
        return;
    }
    set_norm(&rem);
    set_norm(&add);
    re_set kept = {0};
    set_subtract(&p->tmp, in, &rem, &kept);
    set_union(&p->tmp, &kept, &add, out);
}

static void word_set_raw(re_parser *p, re_set *out)
{
    set_reset(out);
    set_push(&p->tmp, out, '0', '9');
    set_push(&p->tmp, out, 'A', 'Z');
    set_push(&p->tmp, out, '_', '_');
    set_push(&p->tmp, out, 'a', 'z');
    if (p->uni && p->icase) {
        for (uint32_t i = 0; i < EMBI_RE_NFOLD_U; i++) {
            uint32_t from = embi_re_fold_u[i].from;
            uint32_t to = embi_re_fold_u[i].to;
            if (is_word_basic(to) && !is_word_basic(from)) {
                set_push(&p->tmp, out, from, from);
            }
        }
    }
    set_norm(out);
}

/* Applies a class escape: a complement (\W, \D, \S, \P) of the base set, closed under case
 * folding in v mode. In u and non-v modes the case closure happens once, at the class node.
 * Scratch in, scratch out. */
static void make_set_escape(re_parser *p, const re_set *base, bool neg, re_set *out)
{
    set_reset(out);
    re_set uni_set = {0};
    if (p->v && p->icase) {
        re_set img = {0};
        canon_set(p, base, true, &img);
        if (neg) {
            universe(p, &uni_set);
            set_subtract(&p->tmp, &uni_set, &img, out);
        } else {
            *out = img;
        }
        return;
    }
    if (neg) {
        universe(p, &uni_set);
        set_subtract(&p->tmp, &uni_set, base, out);
    } else {
        *out = *base;
    }
}

static void escape_set(re_parser *p, uint32_t c, re_set *out)
{
    bool neg = c == 'D' || c == 'S' || c == 'W';
    uint64_t key = ecache_key(p, 0x1000000u + (c | 0x20), neg);
    const re_set *hit = ecache_get(p, key);
    if (hit) {
        *out = *hit;
        return;
    }
    embi_arena_pos m = embi_arena_mark(&p->tmp);
    re_set base = {0};
    switch (c | 0x20) {
    case 'd':
        set_push(&p->tmp, &base, '0', '9');
        break;
    case 's':
        set_push(&p->tmp, &base, 0x09, 0x0D);
        set_push(&p->tmp, &base, 0x20, 0x20);
        set_push(&p->tmp, &base, 0xA0, 0xA0);
        set_push(&p->tmp, &base, 0x1680, 0x1680);
        set_push(&p->tmp, &base, 0x2000, 0x200A);
        set_push(&p->tmp, &base, 0x2028, 0x2029);
        set_push(&p->tmp, &base, 0x202F, 0x202F);
        set_push(&p->tmp, &base, 0x205F, 0x205F);
        set_push(&p->tmp, &base, 0x3000, 0x3000);
        set_push(&p->tmp, &base, 0xFEFF, 0xFEFF);
        set_norm(&base);
        break;
    default:
        word_set_raw(p, &base);
        break;
    }
    re_set res = {0};
    make_set_escape(p, &base, neg, &res);
    set_persist(p, &res, out);
    embi_arena_reset_to(&p->tmp, m);
    ecache_put(p, key, out);
}

static bool emoji_prop(re_parser *p, const char *name, bool neg, re_cs *cs);
static int emoji_prop_kind(const char *name);

/* \p{...} or \P{...}, with pos at the 'p' or 'P'. cs is non-null in v-mode: the properties of
 * strings (RGI_Emoji, ...) are then added to it, and 'out' is its chars member. */
static bool parse_property(re_parser *p, bool neg, re_set *out, re_cs *cs)
{
    p->pos++;
    if (!at(p, '{')) {
        perr(p, "invalid property name");
        return false;
    }
    p->pos++;
    char buf[96];
    uint32_t n = 0;
    while (p->pos < p->len && p->src[p->pos] != '}') {
        uint32_t c = p->src[p->pos];
        if (c > 127 || n >= sizeof buf - 1) {
            perr(p, "invalid property name");
            return false;
        }
        buf[n++] = (char)c;
        p->pos++;
    }
    if (!at(p, '}')) {
        perr(p, "invalid property name");
        return false;
    }
    p->pos++;
    buf[n] = '\0';
    const embi_re_pname *e;
    char *eq = strchr(buf, '=');
    if (eq) {
        *eq = '\0';
        const char *key = buf;
        const char *val = eq + 1;
        int ns;
        if (strcmp(key, "General_Category") == 0 || strcmp(key, "gc") == 0) {
            ns = EMBI_RE_NS_GC;
        } else if (strcmp(key, "Script") == 0 || strcmp(key, "sc") == 0) {
            ns = EMBI_RE_NS_SC;
        } else if (strcmp(key, "Script_Extensions") == 0 || strcmp(key, "scx") == 0) {
            ns = EMBI_RE_NS_SCX;
        } else {
            perr(p, "invalid property name");
            return false;
        }
        e = prop_find(val, ns);
    } else {
        if (cs) {
            int r = emoji_prop_kind(buf);
            if (r) {
                return emoji_prop(p, buf, neg, cs);
            }
        }
        e = prop_find(buf, EMBI_RE_NS_LONE);
    }
    if (!e) {
        perr(p, "invalid property name");
        return false;
    }
    uint64_t key = ecache_key(p, (uint64_t)(e - embi_re_pnames), neg);
    const re_set *hit = ecache_get(p, key);
    if (hit) {
        *out = *hit;
        return true;
    }
    embi_arena_pos m = embi_arena_mark(&p->tmp);
    re_set base = {0};
    prop_build(p, e, &base);
    re_set res = {0};
    make_set_escape(p, &base, neg, &res);
    set_persist(p, &res, out);
    embi_arena_reset_to(&p->tmp, m);
    ecache_put(p, key, out);
    return true;
}

/* Decodes a named property into a long-lived set (ID_Start, ID_Continue). */
static void prop_persist_named(re_parser *p, const char *name, re_set *out)
{
    const embi_re_pname *e = prop_find(name, EMBI_RE_NS_LONE);
    embi_arena_pos m = embi_arena_mark(&p->tmp);
    re_set base = {0};
    prop_build(p, e, &base);
    set_persist(p, &base, out);
    embi_arena_reset_to(&p->tmp, m);
}

static void u16_push(embi_arena *ar, uint16_t **buf, uint32_t *n, uint32_t *cap, uint16_t unit)
{
    if (*n == *cap) {
        uint32_t nc = *cap ? *cap * 2 : 16;
        uint16_t *nb = embi_arena_alloc(ar, (size_t)nc * sizeof *nb, alignof(uint16_t));
        if (*n) {
            memcpy(nb, *buf, (size_t)*n * sizeof *nb);
        }
        *buf = nb;
        *cap = nc;
    }
    (*buf)[(*n)++] = unit;
}

static bool name_eq(const uint16_t *a, uint32_t alen, const uint16_t *b, uint32_t blen)
{
    return alen == blen && (alen == 0 || memcmp(a, b, (size_t)alen * sizeof *a) == 0);
}

/* RegExpIdentifierName inside <...>. pos is at the '<'. */
static bool parse_group_name(re_parser *p, uint16_t **out, uint32_t *outlen)
{
    p->pos++;
    uint16_t *buf = nullptr;
    uint32_t n = 0;
    uint32_t cap = 0;
    bool first = true;
    for (;;) {
        if (p->pos >= p->len) {
            perr(p, "invalid capture group name");
            return false;
        }
        uint32_t c = cur(p);
        if (c == '>') {
            p->pos++;
            break;
        }
        uint32_t cp;
        if (c == '\\') {
            p->pos++;
            if (!at(p, 'u')) {
                perr(p, "invalid capture group name");
                return false;
            }
            p->pos++;
            if (!parse_u_body(p, &cp)) {
                return false;
            }
        } else {
            cp = read_cp(p, true);
        }
        if (!p->idloaded) {
            p->idloaded = true;
            prop_persist_named(p, "ID_Start", &p->idstart);
            prop_persist_named(p, "ID_Continue", &p->idcont);
        }
        bool ok = first ? (cp == '$' || cp == '_' || set_has(&p->idstart, cp))
                        : (cp == '$' || cp == 0x200C || cp == 0x200D || set_has(&p->idcont, cp));
        if (!ok) {
            perr(p, "invalid capture group name");
            return false;
        }
        first = false;
        if (cp >= 0x10000) {
            u16_push(p->ar, &buf, &n, &cap, (uint16_t)(0xD800 + ((cp - 0x10000) >> 10)));
            u16_push(p->ar, &buf, &n, &cap, (uint16_t)(0xDC00 + ((cp - 0x10000) & 0x3FF)));
        } else {
            u16_push(p->ar, &buf, &n, &cap, (uint16_t)cp);
        }
    }
    if (n == 0) {
        perr(p, "invalid capture group name");
        return false;
    }
    *out = buf;
    *outlen = n;
    return true;
}

/* Two groups with one name conflict unless they sit in different alternatives of the same
 * disjunction (ES2025 duplicate named groups). */
static bool paths_conflict(const re_pathent *a, uint32_t na, const re_pathent *b, uint32_t nb)
{
    uint32_t n = na < nb ? na : nb;
    for (uint32_t k = 0; k < n; k++) {
        if (a[k].dis != b[k].dis) {
            return true;
        }
        if (a[k].alt != b[k].alt) {
            return false;
        }
    }
    return true;
}

static uint32_t name_hash(const uint16_t *name, uint32_t len)
{
    uint32_t h = 2166136261u;
    for (uint32_t i = 0; i < len; i++) {
        h = (h ^ name[i]) * 16777619u;
    }
    return h;
}

static void gname_link(re_parser *p, uint32_t g)
{
    uint32_t b = name_hash(p->gnames[g].name, p->gnames[g].len) & (p->nbuckets - 1);
    p->gnames[g].hnext = p->gbuckets[b];
    p->gbuckets[b] = g + 1;
}

/* The record for a name, or nullptr. */
static re_gname *gname_find(const re_parser *p, const uint16_t *name, uint32_t len)
{
    if (!p->nbuckets) {
        return nullptr;
    }
    for (uint32_t g = p->gbuckets[name_hash(name, len) & (p->nbuckets - 1)]; g;
         g = p->gnames[g - 1].hnext) {
        re_gname *rec = &p->gnames[g - 1];
        if (name_eq(rec->name, rec->len, name, len)) {
            return rec;
        }
    }
    return nullptr;
}

/* Remembers the current disjunction path as the newest group's path of this name. */
static void gname_set_path(re_parser *p, re_gname *rec)
{
    if (p->pathlen > rec->pathcap) {
        rec->path = embi_arena_alloc(p->ar, (size_t)p->pathlen * sizeof(re_pathent),
                                     alignof(re_pathent));
        rec->pathcap = p->pathlen;
    }
    if (p->pathlen) {
        memcpy(rec->path, p->path, (size_t)p->pathlen * sizeof(re_pathent));
    }
    rec->pathlen = p->pathlen;
}

static void gname_add_index(re_parser *p, re_gname *rec, uint32_t index)
{
    if (rec->nidx == rec->capidx) {
        uint32_t nc = rec->capidx ? rec->capidx * 2 : 2;
        uint32_t *ni = u32_array(p->ar, nc);
        if (rec->nidx) {
            memcpy(ni, rec->idx, (size_t)rec->nidx * sizeof *ni);
        }
        rec->idx = ni;
        rec->capidx = nc;
    }
    rec->idx[rec->nidx++] = index;
}

static bool register_name(re_parser *p, uint16_t *name, uint32_t len, uint32_t index)
{
    re_gname *rec = gname_find(p, name, len);
    if (rec) {
        /* The earlier groups of this name already diverge pairwise, so a new group that diverges
         * from the newest one diverges from all of them. */
        if (paths_conflict(rec->path, rec->pathlen, p->path, p->pathlen)) {
            perr(p, "duplicate capture group name");
            return false;
        }
        gname_add_index(p, rec, index);
        gname_set_path(p, rec);
        return true;
    }
    if (p->ngnames == p->capgnames) {
        uint32_t nc = p->capgnames ? p->capgnames * 2 : 8;
        re_gname *ng = embi_arena_alloc(p->ar, (size_t)nc * sizeof *ng, alignof(re_gname));
        if (p->ngnames) {
            memcpy(ng, p->gnames, (size_t)p->ngnames * sizeof *ng);
        }
        p->gnames = ng;
        p->capgnames = nc;
    }
    rec = &p->gnames[p->ngnames++];
    memset(rec, 0, sizeof *rec);
    rec->name = name;
    rec->len = len;
    gname_add_index(p, rec, index);
    gname_set_path(p, rec);
    if (p->ngnames * 2 > p->nbuckets) {
        uint32_t nb = p->nbuckets ? p->nbuckets * 2 : 16;
        p->gbuckets = embi_arena_alloc(p->ar, (size_t)nb * sizeof *p->gbuckets, alignof(uint32_t));
        memset(p->gbuckets, 0, (size_t)nb * sizeof *p->gbuckets);
        p->nbuckets = nb;
        for (uint32_t g = 0; g < p->ngnames; g++) {
            gname_link(p, g);
        }
    } else {
        gname_link(p, p->ngnames - 1);
    }
    return true;
}

static void nameref_add(re_parser *p, re_node *n)
{
    if (p->nnamerefs == p->capnamerefs) {
        uint32_t nc = p->capnamerefs ? p->capnamerefs * 2 : 8;
        re_node **nr = embi_arena_alloc(p->ar, (size_t)nc * sizeof *nr, alignof(re_node *));
        if (p->nnamerefs) {
            memcpy(nr, p->namerefs, (size_t)p->nnamerefs * sizeof *nr);
        }
        p->namerefs = nr;
        p->capnamerefs = nc;
    }
    p->namerefs[p->nnamerefs++] = n;
}

/* out = the long-lived canonicalization image of 's'. Large sets are remembered by content, so a
 * pattern that repeats one big class (for example [\p{L}] under i) builds its image once. */
static void canon_persist(re_parser *p, const re_set *s, bool uni, re_set *out)
{
    bool cacheable = s->n >= 32;
    if (cacheable) {
        for (uint32_t i = 0; i < p->nccache; i++) {
            const re_ccent *c = &p->ccache[i];
            if (c->uni == uni && c->in.n == s->n &&
                (c->in.r == s->r || memcmp(c->in.r, s->r, (size_t)s->n * sizeof *s->r) == 0)) {
                *out = c->out;
                return;
            }
        }
    }
    re_set in = *s;
    if (cacheable) {
        set_persist(p, s, &in);
    }
    embi_arena_pos m = embi_arena_mark(&p->tmp);
    re_set img = {0};
    canon_set(p, &in, uni, &img);
    set_persist(p, &img, out);
    embi_arena_reset_to(&p->tmp, m);
    if (cacheable) {
        uint32_t slot;
        if (p->nccache < RE_CCACHE) {
            slot = p->nccache++;
        } else {
            slot = p->cnext;
            p->cnext = (p->cnext + 1) % RE_CCACHE;
        }
        p->ccache[slot].in = in;
        p->ccache[slot].out = *out;
        p->ccache[slot].uni = uni;
    }
}

/* A class-set or class node from a canonical set. Under i (non-v), the set is closed under
 * Canonicalize here; under v the operands were already folded. */
static re_node *class_node_from_set(re_parser *p, const re_set *s, bool neg)
{
    re_node *n = node_new(p, N_CLASS);
    if (p->icase) {
        n->flags |= F_ICASE;
    }
    if (neg) {
        n->flags |= F_NEG;
    }
    n->set = embi_arena_alloc(p->ar, sizeof *n->set, alignof(re_set));
    memset(n->set, 0, sizeof *n->set);
    if (p->icase && !p->v) {
        canon_persist(p, s, p->uni, n->set);
    } else {
        set_persist(p, s, n->set); /* a shared set is referenced, not copied */
    }
    return n;
}

static re_node *char_node(re_parser *p, uint32_t cp)
{
    re_node *n = node_new(p, N_CHAR);
    n->value = cp;
    if (p->icase) {
        n->flags |= F_ICASE;
    }
    return n;
}

/* Non-u class atom: a single character or a class escape. */
static bool class_atom(re_parser *p, uint32_t *cp, bool *is_char, re_set *set)
{
    *is_char = true;
    if (!at(p, '\\')) {
        *cp = read_cp(p, p->uni);
        return true;
    }
    p->pos++;
    if (p->pos >= p->len) {
        perr(p, "\\ at end of pattern");
        return false;
    }
    uint32_t c = cur(p);
    switch (c) {
    case 'b':
        p->pos++;
        *cp = 8;
        return true;
    case '-':
        p->pos++;
        *cp = '-';
        return true;
    case 'd': case 'D': case 's': case 'S': case 'w': case 'W':
        p->pos++;
        escape_set(p, c, set);
        *is_char = false;
        return true;
    case 'p': case 'P':
        if (p->uni) {
            if (!parse_property(p, c == 'P', set, nullptr)) {
                return false;
            }
            *is_char = false;
            return true;
        }
        break;
    case 'k':
        if (p->named) {
            perr(p, "invalid escape");
            return false;
        }
        break;
    default:
        break;
    }
    return parse_char_escape(p, true, cp);
}

static void add_atom(re_parser *p, re_set *acc, uint32_t cp, bool is_char, const re_set *set)
{
    if (is_char) {
        set_push(&p->tmp, acc, cp, cp);
    } else if (acc->n == 0 && set->shared) {
        *acc = *set; /* first member: reference the shared set until something is added */
    } else {
        set_add_all(&p->tmp, acc, set);
        set_maybe_norm(acc);
    }
}

/* Non-v class: [ ClassContents ] with pos after the '['. */
static re_node *parse_class_nonv(re_parser *p)
{
    bool neg = false;
    if (at(p, '^')) {
        neg = true;
        p->pos++;
    }
    embi_arena_pos mark = embi_arena_mark(&p->tmp);
    re_set acc = {0}; /* scratch; the node gets a long-lived copy */
    for (;;) {
        if (over_budget(p)) {
            return nullptr;
        }
        if (p->pos >= p->len) {
            perr(p, "unterminated character class");
            return nullptr;
        }
        if (at(p, ']')) {
            break;
        }
        uint32_t lo = 0;
        bool lo_char = false;
        re_set lo_set = {0};
        if (!class_atom(p, &lo, &lo_char, &lo_set)) {
            return nullptr;
        }
        if (p->pos + 1 < p->len && p->src[p->pos] == '-' && p->src[p->pos + 1] != ']') {
            p->pos++;
            uint32_t hi = 0;
            bool hi_char = false;
            re_set hi_set = {0};
            if (!class_atom(p, &hi, &hi_char, &hi_set)) {
                return nullptr;
            }
            if (lo_char && hi_char) {
                if (lo > hi) {
                    perr(p, "range out of order in character class");
                    return nullptr;
                }
                set_push(&p->tmp, &acc, lo, hi);
            } else {
                if (p->uni) {
                    perr(p, "invalid character class");
                    return nullptr;
                }
                add_atom(p, &acc, lo, lo_char, &lo_set);
                set_push(&p->tmp, &acc, '-', '-');
                add_atom(p, &acc, hi, hi_char, &hi_set);
            }
        } else {
            add_atom(p, &acc, lo, lo_char, &lo_set);
        }
    }
    p->pos++;
    set_norm(&acc);
    re_node *node = class_node_from_set(p, &acc, neg);
    embi_arena_reset_to(&p->tmp, mark);
    return node;
}

/* ---- v-mode classes ---- */

static bool v_is_syntax(uint32_t c)
{
    switch (c) {
    case '(': case ')': case '[': case ']': case '{': case '}': case '/': case '-': case '\\':
    case '|':
        return true;
    default:
        return false;
    }
}

static bool v_is_reserved_punct(uint32_t c)
{
    switch (c) {
    case '&': case '-': case '!': case '#': case '%': case ',': case ':': case ';': case '<':
    case '=': case '>': case '@': case '`': case '~':
        return true;
    default:
        return false;
    }
}

static bool v_is_double(uint32_t c)
{
    switch (c) {
    case '&': case '!': case '#': case '$': case '%': case '*': case '+': case ',': case '.':
    case ':': case ';': case '<': case '=': case '>': case '?': case '@': case '^': case '`':
    case '~':
        return true;
    default:
        return false;
    }
}

/* ClassSetCharacter. */
static bool v_set_char(re_parser *p, uint32_t *cp)
{
    if (p->pos >= p->len) {
        perr(p, "unterminated character class");
        return false;
    }
    uint32_t c = cur(p);
    if (c == '\\') {
        uint32_t d = peek(p, 1);
        if (d == RE_NONE) {
            perr(p, "\\ at end of pattern");
            return false;
        }
        if (d == 'b') {
            p->pos += 2;
            *cp = 8;
            return true;
        }
        if (v_is_reserved_punct(d)) {
            p->pos += 2;
            *cp = d;
            return true;
        }
        p->pos++;
        return parse_char_escape(p, true, cp);
    }
    if (v_is_syntax(c)) {
        perr(p, "invalid character in character class");
        return false;
    }
    if (p->pos + 1 < p->len && c == p->src[p->pos + 1] && v_is_double(c)) {
        perr(p, "invalid set operation in character class");
        return false;
    }
    *cp = read_cp(p, true);
    return true;
}

static void cs_fold_chars(re_parser *p, re_set *chars)
{
    if (p->icase) {
        embi_arena_pos m = embi_arena_mark(&p->tmp);
        re_set img = {0};
        canon_set(p, chars, true, &img);
        if (img.r != chars->r) {
            set_persist(p, &img, chars);
        }
        embi_arena_reset_to(&p->tmp, m);
    }
}

/* Total order on class strings: longer first, then by code points. */
static int str_cmp(const re_str *a, const re_str *b)
{
    if (a->n != b->n) {
        return a->n > b->n ? -1 : 1;
    }
    for (uint32_t i = 0; i < a->n; i++) {
        if (a->cp[i] != b->cp[i]) {
            return a->cp[i] < b->cp[i] ? -1 : 1;
        }
    }
    return 0;
}

static int str_qcmp(const void *a, const void *b)
{
    return str_cmp(a, b);
}

/* Sorts and dedupes the strings. Every re_cs leaving v_item/v_contents is in this form, so
 * str_in can binary search. */
static void cs_strs_norm(re_cs *cs)
{
    if (cs->nstrs > 1) {
        SDL_qsort(cs->strs, cs->nstrs, sizeof *cs->strs, str_qcmp);
    }
    uint32_t k = 0;
    for (uint32_t i = 0; i < cs->nstrs; i++) {
        if (k == 0 || str_cmp(&cs->strs[k - 1], &cs->strs[i]) != 0) {
            cs->strs[k++] = cs->strs[i];
        }
    }
    cs->nstrs = k;
}

/* cs must be normalized (cs_strs_norm). */
static bool str_in(const re_cs *cs, const re_str *s)
{
    uint32_t lo = 0;
    uint32_t hi = cs->nstrs;
    while (lo < hi) {
        uint32_t mid = lo + (hi - lo) / 2;
        int c = str_cmp(&cs->strs[mid], s);
        if (c == 0) {
            return true;
        }
        if (c < 0) {
            lo = mid + 1;
        } else {
            hi = mid;
        }
    }
    return false;
}

static void cs_add_str(re_parser *p, re_cs *cs, const re_str *s)
{
    if (cs->nstrs == cs->capstrs) {
        uint32_t nc = cs->capstrs ? cs->capstrs * 2 : 4;
        re_str *ns = embi_arena_alloc(p->ar, (size_t)nc * sizeof *ns, alignof(re_str));
        if (cs->nstrs) {
            memcpy(ns, cs->strs, (size_t)cs->nstrs * sizeof *ns);
        }
        cs->strs = ns;
        cs->capstrs = nc;
    }
    cs->strs[cs->nstrs++] = *s;
}

/* Appends b's members without normalizing; the caller normalizes acc once after the last union
 * (set_norm and cs_strs_norm), keeping a class with N members O(N log N). */
static void cs_union(re_parser *p, re_cs *acc, const re_cs *b)
{
    acc->may_strings = acc->may_strings || b->may_strings;
    if (acc->chars.n == 0 && b->chars.shared) {
        acc->chars = b->chars; /* reference the shared set; a later push copies it */
    } else {
        set_add_all(p->ar, &acc->chars, &b->chars);
        set_maybe_norm(&acc->chars);
    }
    for (uint32_t i = 0; i < b->nstrs; i++) {
        cs_add_str(p, acc, &b->strs[i]);
    }
}

/* Set operations on a v-mode accumulator. 'scr' is the chain's second buffer: the result is built in
 * it and the two are swapped, so a chain of any length holds two sets that grow geometrically, not
 * one set per operator. Class strings are filtered in place (the survivors stay sorted). */
static void cs_intersect(re_parser *p, re_cs *acc, const re_cs *b, re_set *scr)
{
    acc->may_strings = acc->may_strings && b->may_strings;
    set_intersect(p->ar, &acc->chars, &b->chars, scr);
    scr->nnorm = scr->n;
    re_set old = acc->chars;
    acc->chars = *scr;
    *scr = old;
    uint32_t k = 0;
    for (uint32_t i = 0; i < acc->nstrs; i++) {
        if (str_in(b, &acc->strs[i])) {
            acc->strs[k++] = acc->strs[i];
        }
    }
    acc->nstrs = k;
}

static void cs_subtract(re_parser *p, re_cs *acc, const re_cs *b, re_set *scr)
{
    set_subtract(p->ar, &acc->chars, &b->chars, scr);
    scr->nnorm = scr->n;
    re_set old = acc->chars;
    acc->chars = *scr;
    *scr = old;
    uint32_t k = 0;
    for (uint32_t i = 0; i < acc->nstrs; i++) {
        if (!str_in(b, &acc->strs[i])) {
            acc->strs[k++] = acc->strs[i];
        }
    }
    acc->nstrs = k;
}

/* out = all characters minus 'chars', computed in scratch and stored at its exact size. */
static void negate_set(re_parser *p, re_set *chars)
{
    set_norm(chars);
    embi_arena_pos m = embi_arena_mark(&p->tmp);
    re_set uni_set = {0};
    universe(p, &uni_set);
    re_set res = {0};
    set_subtract(&p->tmp, &uni_set, chars, &res);
    set_persist(p, &res, chars);
    embi_arena_reset_to(&p->tmp, m);
}

/* Adds one \q{...} alternative (or one character from it). */
static void cs_add_string(re_parser *p, re_cs *cs, const uint32_t *cps, uint32_t n)
{
    if (n != 1) {
        cs->may_strings = true;
    }
    uint32_t *copy = u32_array(p->ar, n);
    for (uint32_t i = 0; i < n; i++) {
        copy[i] = p->icase ? canon_u(cps[i]) : cps[i];
    }
    if (n == 1) {
        set_push(p->ar, &cs->chars, copy[0], copy[0]);
        return;
    }
    re_str s = {copy, n};
    cs_add_str(p, cs, &s); /* duplicates are removed by cs_strs_norm */
}

#include "js/regexp_emoji.inc"

enum { EMO_BASIC = 1, EMO_KEYCAP = 2, EMO_FLAG = 4, EMO_MOD = 8, EMO_TAG = 16, EMO_ZWJ = 32 };

/* The EMO_* groups of a property-of-strings name, 0 when it is not one. */
static int emoji_prop_kind(const char *name)
{
    static const struct {
        const char *name;
        int kinds;
    } tbl[] = {
        {"Basic_Emoji", EMO_BASIC},
        {"Emoji_Keycap_Sequence", EMO_KEYCAP},
        {"RGI_Emoji_Flag_Sequence", EMO_FLAG},
        {"RGI_Emoji_Modifier_Sequence", EMO_MOD},
        {"RGI_Emoji_Tag_Sequence", EMO_TAG},
        {"RGI_Emoji_ZWJ_Sequence", EMO_ZWJ},
        {"RGI_Emoji", EMO_BASIC | EMO_KEYCAP | EMO_FLAG | EMO_MOD | EMO_TAG | EMO_ZWJ},
    };
    for (size_t i = 0; i < sizeof tbl / sizeof tbl[0]; i++) {
        if (strcmp(name, tbl[i].name) == 0) {
            return tbl[i].kinds;
        }
    }
    return 0;
}

/* Adds the members of a property of strings to cs (v-mode only; its negation is an error). */
static bool emoji_prop(re_parser *p, const char *name, bool neg, re_cs *cs)
{
    if (neg) {
        perr(p, "negated property of strings");
        return false;
    }
    int kinds = emoji_prop_kind(name);
    cs->may_strings = true;
    uint32_t seq[8];
    if (kinds & EMO_BASIC) {
        for (size_t i = 0; i + 1 < sizeof emo_basic1 / sizeof emo_basic1[0]; i += 2) {
            set_push(p->ar, &cs->chars, emo_basic1[i], emo_basic1[i + 1]);
        }
        for (size_t i = 0; i + 1 < sizeof emo_basic2 / sizeof emo_basic2[0]; i += 2) {
            for (uint32_t c = emo_basic2[i]; c <= emo_basic2[i + 1]; c++) {
                seq[0] = c;
                seq[1] = 0xFE0F;
                cs_add_string(p, cs, seq, 2);
            }
        }
    }
    if (kinds & EMO_KEYCAP) {
        for (uint32_t i = 0; i < 12; i++) {
            seq[0] = i < 10 ? 0x30 + i : (i == 10 ? 0x23 : 0x2A);
            seq[1] = 0xFE0F;
            seq[2] = 0x20E3;
            cs_add_string(p, cs, seq, 3);
        }
    }
    if (kinds & EMO_FLAG) {
        for (size_t i = 0; i + 1 < sizeof emo_flags; i += 2) {
            seq[0] = 0x1F1E6u + emo_flags[i];
            seq[1] = 0x1F1E6u + emo_flags[i + 1];
            cs_add_string(p, cs, seq, 2);
        }
    }
    if (kinds & EMO_MOD) {
        for (size_t i = 0; i < sizeof emo_mod_bases / sizeof emo_mod_bases[0]; i++) {
            for (uint32_t m = 0x1F3FB; m <= 0x1F3FF; m++) {
                seq[0] = emo_mod_bases[i];
                seq[1] = m;
                cs_add_string(p, cs, seq, 2);
            }
        }
    }
    if (kinds & EMO_TAG) {
        for (size_t i = 0; i < sizeof emo_tags / sizeof emo_tags[0]; i++) {
            uint32_t n = 0;
            seq[n++] = 0x1F3F4;
            for (const char *t = emo_tags[i]; *t && n < 7; t++) {
                seq[n++] = 0xE0000u + (unsigned char)*t;
            }
            seq[n++] = 0xE007F;
            cs_add_string(p, cs, seq, n);
        }
    }
    if (kinds & EMO_ZWJ) {
        /* Token table offsets, then the sequences: count followed by that many token indexes. */
        uint32_t off[EMO_NTOK];
        size_t o = 0;
        for (uint32_t i = 0; i < EMO_NTOK; i++) {
            off[i] = (uint32_t)o;
            o += 1 + emo_zwj_tok[o];
        }
        uint32_t buf[32];
        for (size_t i = 0; i < sizeof emo_zwj_seq / sizeof emo_zwj_seq[0];) {
            uint32_t cnt = emo_zwj_seq[i++];
            uint32_t n = 0;
            for (uint32_t k = 0; k < cnt; k++) {
                const uint32_t *t = &emo_zwj_tok[off[emo_zwj_seq[i++]]];
                if (k && n < sizeof buf / sizeof buf[0]) {
                    buf[n++] = 0x200D;
                }
                /* Today's table fits the buffer; a longer regenerated sequence is cut rather than
                 * overflowing. */
                for (uint32_t j = 0; j < t[0] && n < sizeof buf / sizeof buf[0]; j++) {
                    buf[n++] = t[1 + j];
                }
            }
            cs_add_string(p, cs, buf, n);
        }
    }
    set_norm(&cs->chars);
    cs_strs_norm(cs);
    return true;
}

static bool v_contents(re_parser *p, re_cs *out);

/* ClassSetOperand or ClassSetRange (when allowed). */
static bool v_item(re_parser *p, bool allow_range, re_cs *out, bool *was_range)
{
    *out = (re_cs){0};
    if (was_range) {
        *was_range = false;
    }
    uint32_t c = cur(p);
    if (c == '[') {
        p->pos++;
        if (p->depth >= RE_MAX_NEST) {
            perr(p, "pattern too complex");
            return false;
        }
        p->depth++;
        bool neg = false;
        if (at(p, '^')) {
            neg = true;
            p->pos++;
        }
        re_cs inner = {0};
        if (!v_contents(p, &inner)) {
            return false;
        }
        p->depth--;
        if (!at(p, ']')) {
            perr(p, "unterminated character class");
            return false;
        }
        p->pos++;
        if (neg) {
            if (inner.may_strings) {
                perr(p, "negated character class may contain strings");
                return false;
            }
            negate_set(p, &inner.chars);
        }
        *out = inner;
        return true;
    }
    if (c == '\\' && peek(p, 1) == 'q') {
        p->pos += 2;
        if (!at(p, '{')) {
            perr(p, "invalid escape");
            return false;
        }
        p->pos++;
        uint32_t *buf = nullptr;
        uint32_t bn = 0;
        uint32_t bcap = 0;
        for (;;) {
            if (p->pos >= p->len) {
                perr(p, "unterminated class string disjunction");
                return false;
            }
            uint32_t d = cur(p);
            if (d == '}' || d == '|') {
                cs_add_string(p, out, buf, bn);
                bn = 0;
                p->pos++;
                if (d == '}') {
                    break;
                }
                continue;
            }
            uint32_t cp;
            if (!v_set_char(p, &cp)) {
                return false;
            }
            if (bn == bcap) {
                uint32_t nc = bcap ? bcap * 2 : 8;
                uint32_t *nb = u32_array(p->ar, nc);
                if (bn) {
                    memcpy(nb, buf, (size_t)bn * sizeof *nb);
                }
                buf = nb;
                bcap = nc;
            }
            buf[bn++] = cp;
        }
        set_norm(&out->chars);
        cs_strs_norm(out);
        return true;
    }
    if (c == '\\' && (peek(p, 1) == 'd' || peek(p, 1) == 'D' || peek(p, 1) == 's' ||
                      peek(p, 1) == 'S' || peek(p, 1) == 'w' || peek(p, 1) == 'W')) {
        uint32_t e = peek(p, 1);
        p->pos += 2;
        re_set s = {0};
        escape_set(p, e, &s);
        out->chars = s;
        return true;
    }
    if (c == '\\' && (peek(p, 1) == 'p' || peek(p, 1) == 'P')) {
        bool neg = peek(p, 1) == 'P';
        p->pos++;
        return parse_property(p, neg, &out->chars, out);
    }
    uint32_t lo;
    if (!v_set_char(p, &lo)) {
        return false;
    }
    if (allow_range && p->pos + 1 < p->len && p->src[p->pos] == '-' && p->src[p->pos + 1] != '-') {
        p->pos++;
        uint32_t hi;
        if (!v_set_char(p, &hi)) {
            return false;
        }
        if (lo > hi) {
            perr(p, "range out of order in character class");
            return false;
        }
        set_push(p->ar, &out->chars, lo, hi);
        cs_fold_chars(p, &out->chars);
        set_norm(&out->chars);
        if (was_range) {
            *was_range = true;
        }
        return true;
    }
    set_push(p->ar, &out->chars, lo, lo);
    cs_fold_chars(p, &out->chars);
    set_norm(&out->chars);
    return true;
}

/* ClassContents[+UnicodeSets]: a union, an intersection or a subtraction. Stops before the ']'. */
static bool v_contents(re_parser *p, re_cs *out)
{
    *out = (re_cs){0};
    if (at(p, ']')) {
        return true;
    }
    re_cs acc = {0};
    re_set scr = {0}; /* second buffer for && and -- chains */
    bool was_range = false;
    if (!v_item(p, true, &acc, &was_range)) {
        return false;
    }
    if (at2(p, '&')) {
        if (was_range) {
            perr(p, "invalid set operation");
            return false;
        }
        while (at2(p, '&')) {
            p->pos += 2;
            if (at(p, '&')) {
                perr(p, "invalid set operation");
                return false;
            }
            if (over_budget(p)) {
                return false;
            }
            re_cs op = {0};
            if (!v_item(p, false, &op, nullptr)) {
                return false;
            }
            cs_intersect(p, &acc, &op, &scr);
        }
        if (!at(p, ']')) {
            perr(p, "invalid set operation");
            return false;
        }
    } else if (at2(p, '-')) {
        if (was_range) {
            perr(p, "invalid set operation");
            return false;
        }
        while (at2(p, '-')) {
            p->pos += 2;
            if (over_budget(p)) {
                return false;
            }
            re_cs op = {0};
            if (!v_item(p, false, &op, nullptr)) {
                return false;
            }
            cs_subtract(p, &acc, &op, &scr);
        }
        if (!at(p, ']')) {
            perr(p, "invalid set operation");
            return false;
        }
    } else {
        while (!at(p, ']')) {
            if (over_budget(p)) {
                return false;
            }
            if (p->pos >= p->len) {
                perr(p, "unterminated character class");
                return false;
            }
            if (at2(p, '&') || at2(p, '-')) {
                perr(p, "invalid set operation");
                return false;
            }
            re_cs item = {0};
            if (!v_item(p, true, &item, nullptr)) {
                return false;
            }
            cs_union(p, &acc, &item);
        }
        set_norm(&acc.chars);
        cs_strs_norm(&acc);
    }
    *out = acc;
    return true;
}

/* A v-mode class as an AST: strings become alternatives, longest first, then the single
 * characters (ECMA-262 CompileToCharSet order). */
static re_node *cs_to_node(re_parser *p, re_cs *cs)
{
    set_norm(&cs->chars);
    re_node *chars_node = nullptr;
    if (cs->chars.n || cs->nstrs == 0) {
        chars_node = node_new(p, N_CLASS);
        if (p->icase) {
            chars_node->flags |= F_ICASE;
        }
        chars_node->set = embi_arena_alloc(p->ar, sizeof *chars_node->set, alignof(re_set));
        *chars_node->set = cs->chars;
    }
    if (cs->nstrs == 0) {
        return chars_node;
    }
    /* cs_strs_norm leaves the strings sorted by length, longest first. */
    cs_strs_norm(cs);
    const re_str *order = cs->strs;
    re_node *alt = node_new(p, N_ALT);
    re_node *last = nullptr;
    for (uint32_t i = 0; i < cs->nstrs; i++) {
        if (order[i].n == 0) {
            continue;
        }
        re_node *seq = node_new(p, N_SEQ);
        re_node *tail = nullptr;
        for (uint32_t k = 0; k < order[i].n; k++) {
            re_node *ch = char_node(p, order[i].cp[k]);
            if (!tail) {
                seq->child = ch;
            } else {
                tail->next = ch;
            }
            tail = ch;
        }
        if (!last) {
            alt->child = seq;
        } else {
            last->next = seq;
        }
        last = seq;
    }
    if (chars_node) {
        if (!last) {
            alt->child = chars_node;
        } else {
            last->next = chars_node;
        }
        last = chars_node;
    }
    /* The empty string is tried after the single characters (ECMA-262 CompileToCharSet order). */
    for (uint32_t i = 0; i < cs->nstrs; i++) {
        if (order[i].n != 0) {
            continue;
        }
        re_node *seq = node_new(p, N_SEQ);
        if (!last) {
            alt->child = seq;
        } else {
            last->next = seq;
        }
        last = seq;
    }
    return alt;
}

/* Class, with pos at the '['. */
static re_node *parse_class(re_parser *p)
{
    p->pos++;
    if (!p->v) {
        return parse_class_nonv(p);
    }
    if (p->depth >= RE_MAX_NEST) {
        perr(p, "pattern too complex");
        return nullptr;
    }
    bool neg = false;
    if (at(p, '^')) {
        neg = true;
        p->pos++;
    }
    re_cs cs = {0};
    p->depth++;
    if (!v_contents(p, &cs)) {
        return nullptr;
    }
    p->depth--;
    if (!at(p, ']')) {
        perr(p, "unterminated character class");
        return nullptr;
    }
    p->pos++;
    if (neg) {
        if (cs.may_strings) {
            perr(p, "negated character class may contain strings");
            return nullptr;
        }
        negate_set(p, &cs.chars);
    }
    return cs_to_node(p, &cs);
}

/* ---- Escapes outside classes ---- */

static re_node *parse_atom_escape(re_parser *p)
{
    p->pos++;
    if (p->pos >= p->len) {
        perr(p, "\\ at end of pattern");
        return nullptr;
    }
    uint32_t c = cur(p);
    switch (c) {
    case 'd': case 'D': case 's': case 'S': case 'w': case 'W': {
        p->pos++;
        re_set s = {0};
        escape_set(p, c, &s);
        return class_node_from_set(p, &s, false);
    }
    case 'p': case 'P':
        if (p->uni) {
            re_cs pcs = {0};
            if (!parse_property(p, c == 'P', &pcs.chars, p->v ? &pcs : nullptr)) {
                return nullptr;
            }
            if (pcs.nstrs) {
                return cs_to_node(p, &pcs);
            }
            return class_node_from_set(p, &pcs.chars, false);
        }
        break;
    case 'k':
        if (p->named) {
            p->pos++;
            if (!at(p, '<')) {
                perr(p, "invalid named reference");
                return nullptr;
            }
            re_node *n = node_new(p, N_NAMEREF);
            if (p->icase) {
                n->flags |= F_ICASE;
            }
            if (!parse_group_name(p, &n->name, &n->namelen)) {
                return nullptr;
            }
            nameref_add(p, n);
            return n;
        }
        break;
    case '1': case '2': case '3': case '4': case '5': case '6': case '7': case '8': case '9': {
        uint32_t start = p->pos;
        uint32_t val = 0;
        read_decimal(p, &val);
        if (val <= p->total_groups) {
            re_node *n = node_new(p, N_BACKREF);
            n->list = u32_array(p->ar, 1);
            n->list[0] = val;
            n->nlist = 1;
            if (p->icase) {
                n->flags |= F_ICASE;
            }
            return n;
        }
        if (p->uni) {
            perr(p, "invalid escape");
            return nullptr;
        }
        p->pos = start;
        break;
    }
    default:
        break;
    }
    uint32_t cp;
    if (!parse_char_escape(p, false, &cp)) {
        return nullptr;
    }
    return char_node(p, cp);
}

/* ---- Groups and lookarounds ---- */

static bool is_mod_char(uint32_t c)
{
    return c == 'i' || c == 'm' || c == 's';
}

static uint32_t mod_bit(uint32_t c)
{
    return c == 'i' ? 1u : (c == 'm' ? 2u : 4u);
}

static re_node *parse_disjunction(re_parser *p);

/* A group that is not a lookaround. pos is at the '('. */
static re_node *parse_group(re_parser *p)
{
    p->pos++;
    if (p->depth >= RE_MAX_NEST) {
        perr(p, "pattern too complex");
        return nullptr;
    }
    bool save_i = p->icase;
    bool save_m = p->multi;
    bool save_s = p->dotall;
    uint32_t index = 0;
    bool capture = false;
    if (at(p, '?')) {
        uint32_t c2 = peek(p, 1);
        if (c2 == ':') {
            p->pos += 2;
        } else if (c2 == '<') {
            p->pos++;
            uint16_t *name = nullptr;
            uint32_t nlen = 0;
            if (!parse_group_name(p, &name, &nlen)) {
                return nullptr;
            }
            index = ++p->ngroups;
            capture = true;
            if (!register_name(p, name, nlen, index)) {
                return nullptr;
            }
        } else if (is_mod_char(c2) || c2 == '-') {
            p->pos++;
            uint32_t add = 0;
            uint32_t rem = 0;
            bool dash = false;
            while (is_mod_char(cur(p))) {
                uint32_t bit = mod_bit(cur(p));
                if (add & bit) {
                    perr(p, "repeated flag in group");
                    return nullptr;
                }
                add |= bit;
                p->pos++;
            }
            if (at(p, '-')) {
                dash = true;
                p->pos++;
                while (is_mod_char(cur(p))) {
                    uint32_t bit = mod_bit(cur(p));
                    if ((rem & bit) || (add & bit)) {
                        perr(p, "repeated flag in group");
                        return nullptr;
                    }
                    rem |= bit;
                    p->pos++;
                }
            }
            if (!at(p, ':') || (dash && add == 0 && rem == 0)) {
                perr(p, "invalid group");
                return nullptr;
            }
            p->pos++;
            if (add & 1u) {
                p->icase = true;
            }
            if (add & 2u) {
                p->multi = true;
            }
            if (add & 4u) {
                p->dotall = true;
            }
            if (rem & 1u) {
                p->icase = false;
            }
            if (rem & 2u) {
                p->multi = false;
            }
            if (rem & 4u) {
                p->dotall = false;
            }
        } else {
            perr(p, "invalid group");
            return nullptr;
        }
    } else {
        index = ++p->ngroups;
        capture = true;
    }
    p->depth++;
    re_node *body = parse_disjunction(p);
    p->depth--;
    if (p->failed) {
        return nullptr;
    }
    if (!at(p, ')')) {
        perr(p, "unterminated group");
        return nullptr;
    }
    p->pos++;
    p->icase = save_i;
    p->multi = save_m;
    p->dotall = save_s;
    if (!capture) {
        return body;
    }
    re_node *g = node_new(p, N_GROUP);
    g->value = index;
    g->child = body;
    return g;
}

/* (?= (?! (?<= (?<! with pos at the '('. */
static re_node *parse_look(re_parser *p, bool behind, bool neg)
{
    p->pos += behind ? 4 : 3;
    if (p->depth >= RE_MAX_NEST) {
        perr(p, "pattern too complex");
        return nullptr;
    }
    p->depth++;
    re_node *body = parse_disjunction(p);
    p->depth--;
    if (p->failed) {
        return nullptr;
    }
    if (!at(p, ')')) {
        perr(p, "unterminated group");
        return nullptr;
    }
    p->pos++;
    re_node *n = node_new(p, N_LOOK);
    n->child = body;
    if (behind) {
        n->flags |= F_BEHIND;
    }
    if (neg) {
        n->flags |= F_NEG;
    }
    return n;
}

/* PatternCharacter, '.', '(' ..., '[' ..., or an escape. */
static re_node *parse_atom(re_parser *p)
{
    uint32_t c = cur(p);
    switch (c) {
    case '.': {
        p->pos++;
        re_node *n = node_new(p, N_ANY);
        if (p->dotall) {
            n->flags |= F_DOTALL;
        }
        return n;
    }
    case '(':
        return parse_group(p);
    case '[':
        return parse_class(p);
    case '\\':
        return parse_atom_escape(p);
    case '*':
    case '+':
    case '?':
        perr(p, "nothing to repeat");
        return nullptr;
    case '{': {
        uint32_t save = p->pos;
        uint32_t mn = 0;
        uint32_t mx = 0;
        if (p->uni) {
            perr(p, "lone quantifier brackets");
            return nullptr;
        }
        p->pos++;
        bool valid = read_decimal(p, &mn);
        if (valid) {
            if (at(p, ',')) {
                p->pos++;
                if (!read_decimal(p, &mx)) {
                    mx = RE_INF;
                }
            } else {
                mx = mn;
            }
            valid = at(p, '}');
        }
        p->pos = save;
        if (valid) {
            perr(p, "nothing to repeat");
            return nullptr;
        }
        p->pos++;
        return char_node(p, '{');
    }
    case '}':
    case ']':
        if (p->uni) {
            perr(p, "lone quantifier brackets");
            return nullptr;
        }
        p->pos++;
        return char_node(p, c);
    default:
        break;
    }
    uint32_t cp = read_cp(p, p->uni);
    return char_node(p, cp);
}

/* Quantifier after an atom, if any. Returns false when there is none (or on error). */
static bool parse_quantifier(re_parser *p, uint32_t *min, uint32_t *max, bool *greedy)
{
    uint32_t c = cur(p);
    if (c == '*') {
        *min = 0;
        *max = RE_INF;
        p->pos++;
    } else if (c == '+') {
        *min = 1;
        *max = RE_INF;
        p->pos++;
    } else if (c == '?') {
        *min = 0;
        *max = 1;
        p->pos++;
    } else if (c == '{') {
        uint32_t save = p->pos;
        bool ok = false;
        p->pos++;
        if (read_decimal(p, min)) {
            if (at(p, ',')) {
                p->pos++;
                if (!read_decimal(p, max)) {
                    *max = RE_INF;
                }
            } else {
                *max = *min;
            }
            ok = at(p, '}');
            if (ok) {
                p->pos++;
            }
        }
        if (!ok) {
            p->pos = save;
            if (p->uni) {
                perr(p, "incomplete quantifier");
            }
            return false;
        }
        if (*min > *max) {
            perr(p, "numbers out of order in {} quantifier");
            return false;
        }
    } else {
        return false;
    }
    *greedy = true;
    if (at(p, '?')) {
        *greedy = false;
        p->pos++;
    }
    return true;
}

/* Term: an assertion, or an atom with an optional quantifier. */
static re_node *parse_term(re_parser *p)
{
    if (over_budget(p)) {
        return nullptr;
    }
    uint32_t c = cur(p);
    if (c == '^') {
        p->pos++;
        re_node *n = node_new(p, N_BOL);
        if (p->multi) {
            n->flags |= F_MULTI;
        }
        return n;
    }
    if (c == '$') {
        p->pos++;
        re_node *n = node_new(p, N_EOL);
        if (p->multi) {
            n->flags |= F_MULTI;
        }
        return n;
    }
    if (c == '\\' && (peek(p, 1) == 'b' || peek(p, 1) == 'B')) {
        bool neg = peek(p, 1) == 'B';
        p->pos += 2;
        re_node *n = node_new(p, N_WORDB);
        if (neg) {
            n->flags |= F_NEG;
        }
        if (p->uni && p->icase) {
            n->flags |= F_WORDX;
        }
        return n;
    }
    uint32_t g0 = p->ngroups;
    re_node *atom;
    bool quantifiable = true;
    if (c == '(' && peek(p, 1) == '?' && (peek(p, 2) == '=' || peek(p, 2) == '!')) {
        atom = parse_look(p, false, peek(p, 2) == '!');
        quantifiable = !p->uni; /* Annex B: lookaheads are quantifiable without u or v */
    } else if (c == '(' && peek(p, 1) == '?' && peek(p, 2) == '<' &&
               (peek(p, 3) == '=' || peek(p, 3) == '!')) {
        atom = parse_look(p, true, peek(p, 3) == '!');
        quantifiable = false;
    } else {
        atom = parse_atom(p);
    }
    if (p->failed) {
        return nullptr;
    }
    uint32_t min;
    uint32_t max;
    bool greedy;
    if (!parse_quantifier(p, &min, &max, &greedy)) {
        if (p->failed) {
            return nullptr;
        }
        return atom;
    }
    if (!quantifiable) {
        perr(p, "invalid quantifier");
        return nullptr;
    }
    re_node *q = node_new(p, N_QUANT);
    q->child = atom;
    q->min = min;
    q->max = max;
    if (greedy) {
        q->flags |= F_GREEDY;
    }
    if (p->ngroups > g0) {
        q->cap_lo = g0 + 1;
        q->cap_hi = p->ngroups + 1;
    }
    return q;
}

static re_node *parse_alternative(re_parser *p)
{
    re_node *seq = node_new(p, N_SEQ);
    re_node *last = nullptr;
    while (p->pos < p->len && p->src[p->pos] != '|' && p->src[p->pos] != ')') {
        re_node *t = parse_term(p);
        if (p->failed) {
            return nullptr;
        }
        if (!last) {
            seq->child = t;
        } else {
            last->next = t;
        }
        last = t;
    }
    return seq;
}

static re_node *parse_disjunction(re_parser *p)
{
    uint32_t dis = ++p->dis_counter;
    re_node *first = nullptr;
    re_node *last = nullptr;
    uint32_t nalts = 0;
    for (uint32_t alt = 0;; alt++) {
        if (p->pathlen >= RE_PATH_MAX) {
            perr(p, "pattern too complex");
            return nullptr;
        }
        p->path[p->pathlen].dis = dis;
        p->path[p->pathlen].alt = alt;
        p->pathlen++;
        re_node *seq = parse_alternative(p);
        p->pathlen--;
        if (p->failed) {
            return nullptr;
        }
        if (!first) {
            first = seq;
        } else {
            last->next = seq;
        }
        last = seq;
        nalts++;
        if (at(p, '|')) {
            p->pos++;
            continue;
        }
        break;
    }
    if (nalts == 1) {
        return first;
    }
    re_node *n = node_new(p, N_ALT);
    n->child = first;
    return n;
}

/* Counts capture groups and detects named groups, skipping escapes and classes. */
static void prescan(const uint16_t *s, uint32_t n, bool v, uint32_t *groups, bool *named)
{
    uint32_t g = 0;
    bool nm = false;
    uint32_t depth = 0;
    uint32_t i = 0;
    while (i < n) {
        uint16_t c = s[i];
        if (c == '\\') {
            i += 2;
            continue;
        }
        if (depth) {
            if (c == '[' && v) {
                depth++;
            } else if (c == ']') {
                depth--;
            }
            i++;
            continue;
        }
        if (c == '[') {
            depth = 1;
        } else if (c == '(') {
            if (i + 1 < n && s[i + 1] == '?') {
                if (i + 3 < n && s[i + 2] == '<' && s[i + 3] != '=' && s[i + 3] != '!') {
                    g++;
                    nm = true;
                }
            } else {
                g++;
            }
        }
        i++;
    }
    *groups = g;
    *named = nm;
}

/* Every \k<name> shares the name's index array; nothing is copied per reference. */
static bool resolve_namerefs(re_parser *p)
{
    for (uint32_t i = 0; i < p->nnamerefs; i++) {
        re_node *n = p->namerefs[i];
        const re_gname *rec = gname_find(p, n->name, n->namelen);
        if (!rec) {
            perr(p, "invalid named capture referenced");
            return false;
        }
        n->list = rec->idx;
        n->nlist = rec->nidx;
        n->type = N_BACKREF;
    }
    return true;
}

static re_node *parse_pattern(re_parser *p)
{
    re_node *root = parse_disjunction(p);
    if (p->failed) {
        return nullptr;
    }
    if (p->pos < p->len) {
        perr(p, p->src[p->pos] == ')' ? "unmatched ')'" : "unexpected character");
        return nullptr;
    }
    if (!resolve_namerefs(p)) {
        return nullptr;
    }
    return root;
}

/* ---------- Code generation ---------- */

typedef struct {
    embi_arena *ar;
    bool uni;
    re_inst *code;
    uint32_t ncode;
    uint32_t capcode;
    re_class *classes;
    uint32_t ncls;
    uint32_t capcls;
    re_range *pool;
    uint32_t npool;
    uint32_t cappool;
    uint32_t *lists;
    uint32_t nlists;
    uint32_t caplists;
    uint32_t reg_base;
    uint32_t nregs;
    uint32_t *chash; /* open-addressing index of classes (class index + 1, 0 = empty) */
    uint32_t chash_cap;
    struct re_lent *lmap; /* backref lists already emitted, keyed by the (shared) array address */
    uint32_t lmap_cap;
    uint32_t lmap_n;
} cgen;

typedef struct re_lent {
    const uint32_t *items;
    uint32_t off;
} re_lent;

static uint32_t emit(cgen *g, uint8_t op, uint8_t f, uint32_t a, uint32_t b, uint32_t c, uint32_t d)
{
    if (g->ncode == g->capcode) {
        uint32_t nc = g->capcode ? g->capcode * 2 : 64;
        re_inst *ni = embi_arena_alloc(g->ar, (size_t)nc * sizeof *ni, alignof(re_inst));
        if (g->ncode) {
            memcpy(ni, g->code, (size_t)g->ncode * sizeof *ni);
        }
        g->code = ni;
        g->capcode = nc;
    }
    re_inst *ins = &g->code[g->ncode];
    ins->op = op;
    ins->f = f;
    ins->pad = 0;
    ins->a = a;
    ins->b = b;
    ins->c = c;
    ins->d = d;
    return g->ncode++;
}

static uint32_t class_hash(const re_set *s, uint8_t fold)
{
    uint32_t h = 2166136261u ^ fold;
    h = (h ^ s->n) * 16777619u;
    for (uint32_t i = 0; i < s->n; i++) {
        h = (h ^ s->r[i].lo) * 16777619u;
        h = (h ^ s->r[i].hi) * 16777619u;
        h ^= h >> 15;
    }
    return h;
}

static bool class_same(const cgen *g, const re_class *old, const re_set *s, uint8_t fold)
{
    return old->fold == fold && old->rn == s->n &&
           (s->n == 0 || memcmp(g->pool + old->roff, s->r, (size_t)s->n * sizeof *s->r) == 0);
}

static void chash_insert(cgen *g, uint32_t idx)
{
    const re_class *c = &g->classes[idx];
    re_set tmp = {.r = c->rn ? g->pool + c->roff : nullptr, .n = c->rn, .cap = c->rn};
    uint32_t m = g->chash_cap - 1;
    uint32_t h = class_hash(&tmp, c->fold) & m;
    while (g->chash[h]) {
        h = (h + 1) & m;
    }
    g->chash[h] = idx + 1;
}

static uint32_t add_class(cgen *g, const re_set *s, uint8_t fold)
{
    /* Amortized O(1) lookup keeps compilation linear in the pattern size. */
    if (g->chash_cap) {
        uint32_t m = g->chash_cap - 1;
        for (uint32_t h = class_hash(s, fold) & m; g->chash[h]; h = (h + 1) & m) {
            if (class_same(g, &g->classes[g->chash[h] - 1], s, fold)) {
                return g->chash[h] - 1;
            }
        }
    }
    if ((g->ncls + 1) * 2 > g->chash_cap) {
        uint32_t nc = g->chash_cap ? g->chash_cap * 2 : 64;
        g->chash = embi_arena_alloc(g->ar, (size_t)nc * sizeof *g->chash, alignof(uint32_t));
        memset(g->chash, 0, (size_t)nc * sizeof *g->chash);
        g->chash_cap = nc;
        /* Re-index after the pool grows below; insertion of old classes uses their pool offsets. */
        for (uint32_t k = 0; k < g->ncls; k++) {
            chash_insert(g, k);
        }
    }
    if (g->ncls == g->capcls) {
        uint32_t nc = g->capcls ? g->capcls * 2 : 16;
        re_class *nk = embi_arena_alloc(g->ar, (size_t)nc * sizeof *nk, alignof(re_class));
        if (g->ncls) {
            memcpy(nk, g->classes, (size_t)g->ncls * sizeof *nk);
        }
        g->classes = nk;
        g->capcls = nc;
    }
    if (g->npool + s->n > g->cappool) {
        uint32_t nc = g->cappool ? g->cappool * 2 : 256;
        while (nc < g->npool + s->n) {
            nc *= 2;
        }
        re_range *np = embi_arena_alloc(g->ar, (size_t)nc * sizeof *np, alignof(re_range));
        if (g->npool) {
            memcpy(np, g->pool, (size_t)g->npool * sizeof *np);
        }
        g->pool = np;
        g->cappool = nc;
    }
    uint32_t idx = g->ncls++;
    re_class *cl = &g->classes[idx];
    memset(cl, 0, sizeof *cl);
    cl->roff = g->npool;
    cl->rn = s->n;
    for (uint32_t i = 0; i < s->n; i++) {
        g->pool[g->npool++] = s->r[i];
    }
    cl->fold = fold;
    for (uint32_t c = 0; c < 256; c++) {
        if (set_has(s, c)) {
            cl->bits[c >> 6] |= (uint64_t)1 << (c & 63);
        }
    }
    chash_insert(g, idx);
    return idx;
}

static uint32_t lent_hash(const uint32_t *items)
{
    uintptr_t x = (uintptr_t)items;
    x ^= x >> 17;
    x *= (uintptr_t)0x9E3779B1u;
    return (uint32_t)(x ^ (x >> 15));
}

static void lmap_insert(cgen *g, const uint32_t *items, uint32_t off)
{
    uint32_t m = g->lmap_cap - 1;
    uint32_t h = lent_hash(items) & m;
    while (g->lmap[h].items) {
        h = (h + 1) & m;
    }
    g->lmap[h].items = items;
    g->lmap[h].off = off;
}

/* Appends a backreference list to the program. Lists that share one array (every \k<name> to
 * one name) are stored once. */
static uint32_t add_list(cgen *g, const uint32_t *items, uint32_t n)
{
    if (g->lmap_cap) {
        uint32_t m = g->lmap_cap - 1;
        for (uint32_t h = lent_hash(items) & m; g->lmap[h].items; h = (h + 1) & m) {
            if (g->lmap[h].items == items) {
                return g->lmap[h].off;
            }
        }
    }
    if (g->nlists + n > g->caplists) {
        uint32_t nc = g->caplists ? g->caplists * 2 : 16;
        while (nc < g->nlists + n) {
            nc *= 2;
        }
        uint32_t *nl = embi_arena_alloc(g->ar, (size_t)nc * sizeof *nl, alignof(uint32_t));
        if (g->nlists) {
            memcpy(nl, g->lists, (size_t)g->nlists * sizeof *nl);
        }
        g->lists = nl;
        g->caplists = nc;
    }
    uint32_t off = g->nlists;
    for (uint32_t i = 0; i < n; i++) {
        g->lists[g->nlists++] = items[i];
    }
    if ((g->lmap_n + 1) * 2 > g->lmap_cap) {
        re_lent *old = g->lmap;
        uint32_t oldcap = g->lmap_cap;
        uint32_t nc = oldcap ? oldcap * 2 : 16;
        g->lmap = embi_arena_alloc(g->ar, (size_t)nc * sizeof *g->lmap, alignof(re_lent));
        memset(g->lmap, 0, (size_t)nc * sizeof *g->lmap);
        g->lmap_cap = nc;
        for (uint32_t i = 0; i < oldcap; i++) {
            if (old[i].items) {
                lmap_insert(g, old[i].items, old[i].off);
            }
        }
    }
    lmap_insert(g, items, off);
    g->lmap_n++;
    return off;
}

static uint32_t cg_reg(cgen *g)
{
    return g->reg_base + g->nregs++;
}

static bool is_simple_atom(const re_node *n)
{
    return n->type == N_CHAR || n->type == N_ANY || n->type == N_CLASS;
}

static void emit_node(cgen *g, const re_node *n, bool back)
{
    uint8_t bf = back ? RF_BACK : 0;
    uint8_t uf = g->uni ? RF_UNI : 0;
    switch (n->type) {
    case N_EMPTY:
        return;
    case N_SEQ:
        if (!back) {
            for (const re_node *k = n->child; k; k = k->next) {
                emit_node(g, k, false);
            }
        } else {
            uint32_t cnt = 0;
            for (const re_node *k = n->child; k; k = k->next) {
                cnt++;
            }
            const re_node **kids =
                embi_arena_alloc(g->ar, (size_t)(cnt ? cnt : 1) * sizeof *kids, alignof(re_node *));
            uint32_t i = 0;
            for (const re_node *k = n->child; k; k = k->next) {
                kids[i++] = k;
            }
            while (i > 0) {
                emit_node(g, kids[--i], true);
            }
        }
        return;
    case N_ALT: {
        uint32_t cnt = 0;
        for (const re_node *k = n->child; k; k = k->next) {
            cnt++;
        }
        uint32_t *jumps = u32_array(g->ar, cnt);
        uint32_t k = 0;
        for (const re_node *alt = n->child; alt; alt = alt->next, k++) {
            if (alt->next) {
                uint32_t split = emit(g, OP_SPLIT, 0, 0, 0, 0, 0);
                g->code[split].a = split + 1;
                emit_node(g, alt, back);
                jumps[k] = emit(g, OP_JMP, 0, 0, 0, 0, 0);
                g->code[split].b = g->ncode;
            } else {
                emit_node(g, alt, back);
            }
        }
        for (uint32_t i = 0; i + 1 < cnt; i++) {
            g->code[jumps[i]].a = g->ncode;
        }
        return;
    }
    case N_CHAR: {
        uint32_t a = n->value;
        uint8_t f = bf | uf;
        if (n->flags & F_ICASE) {
            a = canon_cp(n->value, g->uni);
            f |= RF_ICASE;
        }
        emit(g, OP_CHAR, f, a, 0, 0, 0);
        return;
    }
    case N_ANY:
        emit(g, OP_ANY, bf | uf | ((n->flags & F_DOTALL) ? RF_DOTALL : 0), 0, 0, 0, 0);
        return;
    case N_CLASS: {
        uint8_t fold = FOLD_NONE;
        if (n->flags & F_ICASE) {
            fold = g->uni ? FOLD_U : FOLD_NU;
        }
        uint32_t idx = add_class(g, n->set, fold);
        emit(g, OP_CLASS, bf | uf | ((n->flags & F_NEG) ? RF_NEG : 0), idx, 0, 0, 0);
        return;
    }
    case N_BOL:
        emit(g, OP_BOL, (n->flags & F_MULTI) ? RF_MULTI : 0, 0, 0, 0, 0);
        return;
    case N_EOL:
        emit(g, OP_EOL, (n->flags & F_MULTI) ? RF_MULTI : 0, 0, 0, 0, 0);
        return;
    case N_WORDB: {
        uint8_t f = ((n->flags & F_NEG) ? RF_NEG : 0) | ((n->flags & F_WORDX) ? RF_WORDX : 0);
        emit(g, OP_WORDB, f, 0, 0, 0, 0);
        return;
    }
    case N_GROUP: {
        uint32_t open = back ? 2 * n->value + 1 : 2 * n->value;
        uint32_t close = back ? 2 * n->value : 2 * n->value + 1;
        emit(g, OP_SAVE, 0, open, 0, 0, 0);
        emit_node(g, n->child, back);
        emit(g, OP_SAVE, 0, close, 0, 0, 0);
        return;
    }
    case N_LOOK: {
        uint8_t f = (n->flags & F_NEG) ? RF_NEG : 0;
        bool behind = (n->flags & F_BEHIND) != 0;
        uint32_t lk = emit(g, OP_LOOK, f, 0, 0, 0, 0);
        emit_node(g, n->child, behind);
        emit(g, OP_LOOK_END, f, 0, 0, 0, 0);
        g->code[lk].a = g->ncode;
        return;
    }
    case N_QUANT: {
        if (n->max == 0) {
            return;
        }
        const re_node *c = n->child;
        bool greedy = (n->flags & F_GREEDY) != 0;
        if (is_simple_atom(c)) {
            emit(g, OP_REP_SIMPLE, greedy ? RF_GREEDY : 0, n->min, n->max, 0, 0);
            emit_node(g, c, back);
            return;
        }
        uint32_t cnt = cg_reg(g);
        uint32_t posr = cg_reg(g);
        emit(g, OP_REG_SET, 0, cnt, 0, 0, 0);
        uint32_t loop = emit(g, OP_LOOP, greedy ? RF_GREEDY : 0, cnt, n->min, n->max, 0);
        emit(g, OP_REG_POS, 0, posr, 0, 0, 0);
        if (n->cap_hi > n->cap_lo) {
            emit(g, OP_RESET, 0, 2 * n->cap_lo, 2 * n->cap_hi, 0, 0);
        }
        emit_node(g, c, back);
        emit(g, OP_ITER, 0, cnt, n->min, posr, loop);
        g->code[loop].d = g->ncode;
        return;
    }
    case N_BACKREF: {
        uint8_t f = bf | uf | ((n->flags & F_ICASE) ? RF_ICASE : 0);
        if (n->nlist == 1) {
            emit(g, OP_BACKREF, f, n->list[0], 0, 0, 0);
        } else {
            uint32_t off = add_list(g, n->list, n->nlist);
            emit(g, OP_BACKREF_LIST, f, off, n->nlist, 0, 0);
        }
        return;
    }
    default:
        return;
    }
}

/* ---------- Program assembly ---------- */

static void *dup_u32(const uint32_t *src, uint32_t n)
{
    void *p = xalloc((size_t)n * sizeof(uint32_t));
    if (n) {
        memcpy(p, src, (size_t)n * sizeof(uint32_t));
    }
    return p;
}

static bool class_has(const embi_re_prog *p, const re_class *cl, uint32_t x);

static bool first_bit(const uint64_t *bits, uint32_t u)
{
    return ((bits[u >> 6] >> (u & 63)) & 1) != 0;
}

/* Computes the set of Latin-1 units (plus the high flag for units >= 256) that can begin a match.
 * The walk follows every path from the body start: zero-width instructions are transparent, and
 * each consuming instruction contributes its possible first units. It gives up (no filter) when a
 * path can reach MATCH without consuming, or reaches a backreference, a lookaround or a backward
 * atom. */
static void build_first_set(embi_re_prog *prog)
{
    prog->has_set = false;
    const uint32_t n = prog->ncode;
    if (n < 2) {
        return;
    }
    uint8_t *seen = xalloc(n);
    uint32_t *stack = xalloc((size_t)n * sizeof *stack);
    memset(seen, 0, n);
    uint32_t sp = 0;
    uint64_t bits[4] = {0, 0, 0, 0};
    bool high = false;
    bool ok = true;
    stack[sp++] = 1;
    seen[1] = 1;
    while (sp > 0 && ok) {
        uint32_t pc = stack[--sp];
        const re_inst *ins = &prog->code[pc];
        uint32_t next[2] = {UINT32_MAX, UINT32_MAX};
        switch (ins->op) {
        case OP_CHAR:
        case OP_ANY:
        case OP_CLASS:
            if (ins->f & RF_BACK) {
                ok = false;
                break;
            }
            if (ins->op == OP_CHAR) {
                bool uni = (ins->f & RF_UNI) != 0;
                if (ins->f & RF_ICASE) {
                    high = true; /* a non-Latin-1 character may fold onto it (U+212A, U+017F) */
                    for (uint32_t c = 0; c < 256; c++) {
                        if (canon_cp(c, uni) == ins->a) {
                            bits[c >> 6] |= (uint64_t)1 << (c & 63);
                        }
                    }
                } else if (ins->a < 256) {
                    /* A code point below 256 never matches a unit >= 256, in u mode either. */
                    bits[ins->a >> 6] |= (uint64_t)1 << (ins->a & 63);
                } else {
                    high = true;
                }
            } else if (ins->op == OP_ANY) {
                high = true;
                for (uint32_t c = 0; c < 256; c++) {
                    if ((ins->f & RF_DOTALL) || !RE_LINE_TERM(c)) {
                        bits[c >> 6] |= (uint64_t)1 << (c & 63);
                    }
                }
            } else {
                /* Mirrors atom_step: canonicalize the input unit, test the class, apply negation. */
                const re_class *cl = &prog->classes[ins->a];
                bool neg = (ins->f & RF_NEG) != 0;
                if (neg || cl->fold != FOLD_NONE) {
                    high = true;
                } else {
                    for (uint32_t k = 0; k < cl->rn; k++) {
                        if (prog->pool[cl->roff + k].hi >= 256) {
                            high = true;
                            break;
                        }
                    }
                }
                for (uint32_t c = 0; c < 256; c++) {
                    uint32_t x = c;
                    if (cl->fold != FOLD_NONE) {
                        x = canon_cp(c, cl->fold == FOLD_U);
                    }
                    if (class_has(prog, cl, x) != neg) {
                        bits[c >> 6] |= (uint64_t)1 << (c & 63);
                    }
                }
            }
            break;
        case OP_SPLIT:
            next[0] = ins->a;
            next[1] = ins->b;
            break;
        case OP_JMP:
            next[0] = ins->a;
            break;
        case OP_SAVE:
        case OP_RESET:
        case OP_REG_SET:
        case OP_REG_POS:
        case OP_BOL:
        case OP_EOL:
        case OP_WORDB:
            next[0] = pc + 1;
            break;
        case OP_LOOP:
            next[0] = pc + 1;
            next[1] = ins->d;
            break;
        case OP_ITER:
            next[0] = ins->d;
            break;
        case OP_REP_SIMPLE:
            /* The atom is at pc + 1; the continuation is reachable without consuming when min is 0. */
            next[0] = pc + 1;
            if (ins->a == 0) {
                next[1] = pc + 2;
            }
            break;
        default:
            ok = false;
            break;
        }
        for (uint32_t k = 0; k < 2 && ok; k++) {
            if (next[k] == UINT32_MAX) {
                continue;
            }
            if (next[k] >= n) {
                ok = false;
            } else if (!seen[next[k]]) {
                seen[next[k]] = 1;
                stack[sp++] = next[k];
            }
        }
    }
    xfree(seen, n);
    xfree(stack, (size_t)n * sizeof *stack);
    if (!ok) {
        return;
    }
    if (high && bits[0] == ~(uint64_t)0 && bits[1] == ~(uint64_t)0 && bits[2] == ~(uint64_t)0 &&
        bits[3] == ~(uint64_t)0) {
        return; /* accepts everything: the filter would only cost time */
    }
    prog->has_set = true;
    prog->set_high = high;
    for (int k = 0; k < 4; k++) {
        prog->set_bits[k] = bits[k];
    }
    uint32_t count = 0;
    uint32_t only = UINT32_MAX;
    for (uint32_t c = 0; c < 256; c++) {
        if (first_bit(bits, c)) {
            count++;
            only = c;
        }
    }
    prog->set_single = (count == 1 && !high) ? only : UINT32_MAX;
}

static embi_re_prog *build_prog(cgen *g, const re_parser *p, uint32_t flags)
{
    embi_re_prog *prog = xalloc(sizeof *prog);
    memset(prog, 0, sizeof *prog);
    prog->flags = flags;
    prog->ngroups = p->ngroups;
    prog->nslots_cap = 2 * (p->ngroups + 1);
    prog->nslots = prog->nslots_cap + g->nregs;
    prog->ncode = g->ncode;
    prog->code = xalloc((size_t)g->ncode * sizeof *prog->code);
    memcpy(prog->code, g->code, (size_t)g->ncode * sizeof *prog->code);
    prog->nclasses = g->ncls;
    prog->classes = xalloc((size_t)g->ncls * sizeof *prog->classes);
    if (g->ncls) {
        memcpy(prog->classes, g->classes, (size_t)g->ncls * sizeof *prog->classes);
    }
    prog->npool = g->npool;
    prog->pool = xalloc((size_t)g->npool * sizeof *prog->pool);
    if (g->npool) {
        memcpy(prog->pool, g->pool, (size_t)g->npool * sizeof *prog->pool);
    }
    prog->nlists = g->nlists;
    prog->lists = dup_u32(g->lists, g->nlists);

    uint32_t gcount = p->ngroups + 1;
    prog->name_off = xalloc((size_t)gcount * sizeof(uint32_t));
    prog->name_len = xalloc((size_t)gcount * sizeof(uint32_t));
    uint32_t total = 0;
    for (uint32_t i = 0; i < gcount; i++) {
        prog->name_off[i] = UINT32_MAX;
        prog->name_len[i] = 0;
    }
    for (uint32_t k = 0; k < p->ngnames; k++) {
        total += p->gnames[k].len;
    }
    prog->nnames = total;
    prog->names = xalloc((size_t)total * sizeof(uint16_t));
    uint32_t off = 0;
    for (uint32_t k = 0; k < p->ngnames; k++) {
        const re_gname *gn = &p->gnames[k];
        memcpy(prog->names + off, gn->name, (size_t)gn->len * sizeof(uint16_t));
        for (uint32_t j = 0; j < gn->nidx; j++) {
            prog->name_off[gn->idx[j]] = off; /* groups with one name share its text */
            prog->name_len[gn->idx[j]] = gn->len;
        }
        off += gn->len;
    }

    build_first_set(prog);
    return prog;
}

/* ---------- Public: flags, compile, free, accessors ---------- */

bool embi_re_parse_flags(const uint16_t *s, uint32_t len, uint32_t *flags)
{
    uint32_t f = 0;
    for (uint32_t i = 0; i < len; i++) {
        uint32_t bit;
        switch (s[i]) {
        case 'd': bit = EMBI_RE_FLAG_D; break;
        case 'g': bit = EMBI_RE_FLAG_G; break;
        case 'i': bit = EMBI_RE_FLAG_I; break;
        case 'm': bit = EMBI_RE_FLAG_M; break;
        case 's': bit = EMBI_RE_FLAG_S; break;
        case 'u': bit = EMBI_RE_FLAG_U; break;
        case 'v': bit = EMBI_RE_FLAG_V; break;
        case 'y': bit = EMBI_RE_FLAG_Y; break;
        default:
            return false;
        }
        if (f & bit) {
            return false;
        }
        f |= bit;
    }
    if ((f & EMBI_RE_FLAG_U) && (f & EMBI_RE_FLAG_V)) {
        return false;
    }
    *flags = f;
    return true;
}

embi_re_prog *embi_re_compile(const uint16_t *pattern, uint32_t len, uint32_t flags,
                              embi_re_error *err)
{
    if (err) {
        err->pos = 0;
        err->msg = nullptr;
    }
    if ((flags & EMBI_RE_FLAG_U) && (flags & EMBI_RE_FLAG_V)) {
        if (err) {
            err->msg = "invalid regular expression flags";
        }
        return nullptr;
    }
    bool v = (flags & EMBI_RE_FLAG_V) != 0;
    bool uni = (flags & (EMBI_RE_FLAG_U | EMBI_RE_FLAG_V)) != 0;
    uint32_t groups = 0;
    bool named = false;
    prescan(pattern, len, v, &groups, &named);

    embi_arena ar;
    embi_arena_init(&ar, 4096);
    re_parser p;
    memset(&p, 0, sizeof p);
    p.ar = &ar;
    embi_arena_init(&p.tmp, 16384);
    (void)embi_arena_alloc(&p.tmp, 1, 1); /* keeps a block alive so mark/reset never frees it */
    p.src = pattern;
    p.len = len;
    p.uni = uni;
    p.v = v;
    p.named = uni || named;
    p.icase = (flags & EMBI_RE_FLAG_I) != 0;
    p.multi = (flags & EMBI_RE_FLAG_M) != 0;
    p.dotall = (flags & EMBI_RE_FLAG_S) != 0;
    p.total_groups = groups;
    p.err = err;

    re_node *root = parse_pattern(&p);
    embi_arena_free(&p.tmp);
#ifdef EMBER_LZ_ASSETS
    if (p.setdata != nullptr) {
        embi_free(p.setdata, p.setdata_raw + 1);
    }
#endif
    if (p.failed || !root) {
        embi_arena_free(&ar);
        return nullptr;
    }

    cgen g;
    memset(&g, 0, sizeof g);
    g.ar = &ar;
    g.uni = uni;
    g.reg_base = 2 * (p.ngroups + 1);
    emit(&g, OP_SAVE, 0, 0, 0, 0, 0);
    emit_node(&g, root, false);
    emit(&g, OP_SAVE, 0, 1, 0, 0, 0);
    emit(&g, OP_MATCH, 0, 0, 0, 0, 0);

    embi_re_prog *prog = build_prog(&g, &p, flags);
    embi_arena_free(&ar);
    return prog;
}

void embi_re_free(embi_re_prog *prog)
{
    if (!prog) {
        return;
    }
    uint32_t gcount = prog->ngroups + 1;
    xfree(prog->code, (size_t)prog->ncode * sizeof *prog->code);
    xfree(prog->classes, (size_t)prog->nclasses * sizeof *prog->classes);
    xfree(prog->pool, (size_t)prog->npool * sizeof *prog->pool);
    xfree(prog->lists, (size_t)prog->nlists * sizeof(uint32_t));
    xfree(prog->name_off, (size_t)gcount * sizeof(uint32_t));
    xfree(prog->name_len, (size_t)gcount * sizeof(uint32_t));
    xfree(prog->names, (size_t)prog->nnames * sizeof(uint16_t));
    xfree(prog, sizeof *prog);
}

uint32_t embi_re_flags(const embi_re_prog *prog)
{
    return prog->flags;
}

uint32_t embi_re_group_count(const embi_re_prog *prog)
{
    return prog->ngroups;
}

uint32_t embi_re_capture_slots(const embi_re_prog *prog)
{
    return prog->nslots_cap;
}

const uint16_t *embi_re_group_name(const embi_re_prog *prog, uint32_t group, uint32_t *len)
{
    if (group == 0 || group > prog->ngroups || prog->name_off[group] == UINT32_MAX) {
        if (len) {
            *len = 0;
        }
        return nullptr;
    }
    if (len) {
        *len = prog->name_len[group];
    }
    return prog->names + prog->name_off[group];
}

/* ---------- Matcher ---------- */

typedef struct {
    uint32_t kind;
    uint32_t a;
    uint32_t b;
    uint32_t c;
    uint32_t d;
} bt_entry;

enum {
    BT_BRANCH = 1, /* a: pc, b: pos */
    BT_SLOT,       /* a: slot, b: old value */
    BT_BARRIER,    /* a: continuation pc, b: pos, c: 1 for a negative lookaround */
    BT_SIMPLE,     /* a: continuation pc, b: pos, c: count, d: min count (greedy simple repeat) */
    BT_LAZY,       /* a: atom pc, b: pos, c: count, d: max count (lazy simple repeat) */
};

typedef struct {
    const embi_re_prog *p;
    embi_re_input in;
    uint32_t *slots;
    bt_entry *stack;
    uint32_t sp;
    uint32_t cap;
    bool heap;
    size_t max_bytes;
    const embi_re_limits *lim;
    uint32_t ticks;
} matcher;

static uint32_t unit_at(const embi_re_input *in, uint32_t i)
{
    return in->wide ? ((const uint16_t *)in->units)[i] : ((const uint8_t *)in->units)[i];
}

static bool read_fwd(const embi_re_input *in, uint32_t pos, bool uni, uint32_t *cp, uint32_t *next)
{
    if (pos >= in->len) {
        return false;
    }
    uint32_t c = unit_at(in, pos);
    if (uni && is_lead(c) && pos + 1 < in->len) {
        uint32_t d = unit_at(in, pos + 1);
        if (is_trail(d)) {
            *cp = cp_from_pair(c, d);
            *next = pos + 2;
            return true;
        }
    }
    *cp = c;
    *next = pos + 1;
    return true;
}

static bool read_bwd(const embi_re_input *in, uint32_t pos, bool uni, uint32_t *cp, uint32_t *prev)
{
    if (pos == 0 || pos > in->len) {
        return false;
    }
    uint32_t c = unit_at(in, pos - 1);
    if (uni && is_trail(c) && pos >= 2) {
        uint32_t h = unit_at(in, pos - 2);
        if (is_lead(h)) {
            *cp = cp_from_pair(h, c);
            *prev = pos - 2;
            return true;
        }
    }
    *cp = c;
    *prev = pos - 1;
    return true;
}

static bool read_char(const embi_re_input *in, uint32_t pos, bool back, bool uni, uint32_t *cp,
                      uint32_t *next)
{
    return back ? read_bwd(in, pos, uni, cp, next) : read_fwd(in, pos, uni, cp, next);
}

static bool class_has(const embi_re_prog *p, const re_class *cl, uint32_t x)
{
    if (x < 256) {
        return ((cl->bits[x >> 6] >> (x & 63)) & 1) != 0;
    }
    const re_range *r = p->pool + cl->roff;
    uint32_t lo = 0;
    uint32_t hi = cl->rn;
    while (lo < hi) {
        uint32_t mid = lo + (hi - lo) / 2;
        if (x < r[mid].lo) {
            hi = mid;
        } else if (x > r[mid].hi) {
            lo = mid + 1;
        } else {
            return true;
        }
    }
    return false;
}

/* Matches one character with a CHAR, ANY or CLASS instruction. */
static bool atom_step(matcher *m, const re_inst *ins, uint32_t pos, uint32_t *np)
{
    bool back = (ins->f & RF_BACK) != 0;
    bool uni = (ins->f & RF_UNI) != 0;
    uint32_t cp;
    uint32_t nx;
    if (!read_char(&m->in, pos, back, uni, &cp, &nx)) {
        return false;
    }
    switch (ins->op) {
    case OP_CHAR: {
        bool hit = (ins->f & RF_ICASE) ? canon_cp(cp, uni) == ins->a : cp == ins->a;
        if (!hit) {
            return false;
        }
        break;
    }
    case OP_ANY:
        if (!(ins->f & RF_DOTALL) && RE_LINE_TERM(cp)) {
            return false;
        }
        break;
    case OP_CLASS: {
        const re_class *cl = &m->p->classes[ins->a];
        uint32_t x = cp;
        if (cl->fold != FOLD_NONE) {
            x = canon_cp(cp, cl->fold == FOLD_U);
        }
        bool hit = class_has(m->p, cl, x);
        if (hit == ((ins->f & RF_NEG) != 0)) {
            return false;
        }
        break;
    }
    default:
        return false;
    }
    *np = nx;
    return true;
}

static bool backref_step(matcher *m, uint32_t g, uint8_t f, uint32_t pos, uint32_t *np)
{
    uint32_t s = m->slots[2 * g];
    uint32_t e = m->slots[2 * g + 1];
    if (s == EMBI_RE_UNDEF || e == EMBI_RE_UNDEF) {
        *np = pos;
        return true;
    }
    bool back = (f & RF_BACK) != 0;
    bool uni = (f & RF_UNI) != 0;
    bool icase = (f & RF_ICASE) != 0;
    uint32_t i;
    uint32_t j = pos;
    if (!back) {
        i = s;
        while (i < e) {
            uint32_t c1;
            uint32_t c2;
            uint32_t n1;
            uint32_t n2;
            if (!read_fwd(&m->in, i, uni, &c1, &n1) || !read_fwd(&m->in, j, uni, &c2, &n2)) {
                return false;
            }
            if (icase ? canon_cp(c1, uni) != canon_cp(c2, uni) : c1 != c2) {
                return false;
            }
            i = n1;
            j = n2;
        }
    } else {
        i = e;
        while (i > s) {
            uint32_t c1;
            uint32_t c2;
            uint32_t n1;
            uint32_t n2;
            if (!read_bwd(&m->in, i, uni, &c1, &n1) || !read_bwd(&m->in, j, uni, &c2, &n2)) {
                return false;
            }
            if (icase ? canon_cp(c1, uni) != canon_cp(c2, uni) : c1 != c2) {
                return false;
            }
            i = n1;
            j = n2;
        }
    }
    *np = j;
    return true;
}

static bool bt_grow(matcher *m)
{
    /* Compare entry counts, not byte counts, so a huge max_bytes cannot overflow size_t or uint32_t. */
    if (m->cap > UINT32_MAX / 2 || (size_t)m->cap * 2 > m->max_bytes / sizeof(bt_entry)) {
        return false;
    }
    uint32_t nc = m->cap * 2;
    size_t bytes = (size_t)nc * sizeof(bt_entry);
    bt_entry *ns = embi_alloc(bytes);
    if (m->sp) {
        memcpy(ns, m->stack, (size_t)m->sp * sizeof(bt_entry));
    }
    if (m->heap) {
        embi_free(m->stack, (size_t)m->cap * sizeof(bt_entry));
    }
    m->stack = ns;
    m->cap = nc;
    m->heap = true;
    return true;
}

static bool bt_push(matcher *m, uint32_t kind, uint32_t a, uint32_t b, uint32_t c, uint32_t d)
{
    if (m->sp == m->cap && !bt_grow(m)) {
        return false;
    }
    bt_entry *e = &m->stack[m->sp++];
    e->kind = kind;
    e->a = a;
    e->b = b;
    e->c = c;
    e->d = d;
    return true;
}

/* Sets a slot, recording the old value so backtracking restores it. */
static bool slot_set(matcher *m, uint32_t s, uint32_t v)
{
    if (m->slots[s] == v) {
        return true;
    }
    if (!bt_push(m, BT_SLOT, s, m->slots[s], 0, 0)) {
        return false;
    }
    m->slots[s] = v;
    return true;
}

/* Pops the backtrack stack to the next alternative. Returns false when there is none. */
static bool backtrack(matcher *m, uint32_t *pc, uint32_t *pos)
{
    for (;;) {
        if (m->sp == 0) {
            return false;
        }
        bt_entry *e = &m->stack[m->sp - 1];
        switch (e->kind) {
        case BT_SLOT:
            m->slots[e->a] = e->b;
            m->sp--;
            break;
        case BT_BRANCH:
            *pc = e->a;
            *pos = e->b;
            m->sp--;
            return true;
        case BT_BARRIER: {
            uint32_t cont = e->a;
            uint32_t bpos = e->b;
            bool neg = e->c != 0;
            m->sp--;
            if (neg) {
                *pc = cont;
                *pos = bpos;
                return true;
            }
            break;
        }
        case BT_SIMPLE:
            if (e->c > e->d) {
                const re_inst *atom = &m->p->code[e->a - 1];
                uint32_t cp = 0;
                uint32_t np = e->b;
                if (atom->f & RF_BACK) {
                    read_fwd(&m->in, e->b, (atom->f & RF_UNI) != 0, &cp, &np);
                } else {
                    read_bwd(&m->in, e->b, (atom->f & RF_UNI) != 0, &cp, &np);
                }
                e->b = np;
                e->c--;
                *pc = e->a;
                *pos = np;
                if (e->c == e->d) {
                    m->sp--;
                }
                return true;
            }
            m->sp--;
            break;
        case BT_LAZY: {
            const re_inst *atom = &m->p->code[e->a];
            uint32_t np;
            if (e->c < e->d && atom_step(m, atom, e->b, &np)) {
                e->b = np;
                e->c++;
                *pc = e->a + 1;
                *pos = np;
                if (e->c == e->d) {
                    m->sp--;
                }
                return true;
            }
            m->sp--;
            break;
        }
        default:
            m->sp--;
            break;
        }
    }
}

#define RE_TRY(expr)                                                                             \
    do {                                                                                         \
        if (!(expr)) {                                                                           \
            return EMBI_RE_TOO_COMPLEX;                                                          \
        }                                                                                        \
    } while (0)

static embi_re_status run(matcher *m, uint32_t pc, uint32_t pos)
{
    const embi_re_prog *p = m->p;
    const embi_re_input *in = &m->in;
    const re_inst *code = p->code;
    for (;;) {
        if ((++m->ticks & 0x0FFFu) == 0 && m->lim && m->lim->interrupt &&
            m->lim->interrupt(m->lim->ctx)) {
            return EMBI_RE_INTERRUPTED;
        }
        const re_inst *ins = &code[pc];
        bool ok = true;
        switch (ins->op) {
        case OP_CHAR:
        case OP_ANY:
        case OP_CLASS: {
            uint32_t np;
            if (atom_step(m, ins, pos, &np)) {
                pos = np;
                pc++;
            } else {
                ok = false;
            }
            break;
        }
        case OP_SPLIT:
            RE_TRY(bt_push(m, BT_BRANCH, ins->b, pos, 0, 0));
            pc = ins->a;
            break;
        case OP_JMP:
            pc = ins->a;
            break;
        case OP_SAVE:
            RE_TRY(slot_set(m, ins->a, pos));
            pc++;
            break;
        case OP_RESET:
            for (uint32_t s = ins->a; s < ins->b; s++) {
                RE_TRY(slot_set(m, s, EMBI_RE_UNDEF));
            }
            pc++;
            break;
        case OP_BOL:
            if (pos == 0 || ((ins->f & RF_MULTI) && RE_LINE_TERM(unit_at(in, pos - 1)))) {
                pc++;
            } else {
                ok = false;
            }
            break;
        case OP_EOL:
            if (pos == in->len || ((ins->f & RF_MULTI) && RE_LINE_TERM(unit_at(in, pos)))) {
                pc++;
            } else {
                ok = false;
            }
            break;
        case OP_WORDB: {
            bool wx = (ins->f & RF_WORDX) != 0;
            bool before = pos > 0 && is_word_ch(unit_at(in, pos - 1), wx);
            bool after = pos < in->len && is_word_ch(unit_at(in, pos), wx);
            bool boundary = before != after;
            bool want = (ins->f & RF_NEG) ? !boundary : boundary;
            if (want) {
                pc++;
            } else {
                ok = false;
            }
            break;
        }
        case OP_BACKREF: {
            uint32_t np;
            if (backref_step(m, ins->a, ins->f, pos, &np)) {
                pos = np;
                pc++;
            } else {
                ok = false;
            }
            break;
        }
        case OP_BACKREF_LIST: {
            bool done = false;
            for (uint32_t k = 0; k < ins->b; k++) {
                uint32_t g = p->lists[ins->a + k];
                if (m->slots[2 * g] != EMBI_RE_UNDEF && m->slots[2 * g + 1] != EMBI_RE_UNDEF) {
                    uint32_t np;
                    if (backref_step(m, g, ins->f, pos, &np)) {
                        pos = np;
                        pc++;
                    } else {
                        ok = false;
                    }
                    done = true;
                    break;
                }
            }
            if (!done) {
                pc++;
            }
            break;
        }
        case OP_LOOK:
            RE_TRY(bt_push(m, BT_BARRIER, ins->a, pos, (ins->f & RF_NEG) ? 1u : 0u, 0));
            pc++;
            break;
        case OP_LOOK_END: {
            bool neg = (ins->f & RF_NEG) != 0;
            uint32_t j = m->sp;
            while (j > 0 && m->stack[j - 1].kind != BT_BARRIER) {
                j--;
            }
            if (j == 0) {
                ok = false;
                break;
            }
            uint32_t bi = j - 1;
            bt_entry barrier = m->stack[bi];
            if (!neg) {
                /* Atomic: drop the alternatives inside, keep the capture undo records. */
                uint32_t w = bi;
                for (uint32_t k = bi + 1; k < m->sp; k++) {
                    if (m->stack[k].kind == BT_SLOT) {
                        m->stack[w++] = m->stack[k];
                    }
                }
                m->sp = w;
                pos = barrier.b;
                pc = barrier.a;
            } else {
                /* The body matched, so the negative lookaround fails: undo and backtrack. */
                for (uint32_t k = m->sp; k > bi + 1; k--) {
                    bt_entry *e = &m->stack[k - 1];
                    if (e->kind == BT_SLOT) {
                        m->slots[e->a] = e->b;
                    }
                }
                m->sp = bi;
                ok = false;
            }
            break;
        }
        case OP_REG_SET:
            RE_TRY(slot_set(m, ins->a, 0));
            pc++;
            break;
        case OP_REG_POS:
            RE_TRY(slot_set(m, ins->a, pos));
            pc++;
            break;
        case OP_LOOP: {
            uint32_t cnt = m->slots[ins->a];
            if (cnt < ins->b) {
                pc++;
            } else if (ins->c != RE_INF && cnt >= ins->c) {
                pc = ins->d;
            } else if (ins->f & RF_GREEDY) {
                RE_TRY(bt_push(m, BT_BRANCH, ins->d, pos, 0, 0));
                pc++;
            } else {
                RE_TRY(bt_push(m, BT_BRANCH, pc + 1, pos, 0, 0));
                pc = ins->d;
            }
            break;
        }
        case OP_ITER: {
            uint32_t cnt = m->slots[ins->a];
            /* An iteration past the minimum that consumed nothing is a failure (empty check). */
            if (cnt >= ins->b && pos == m->slots[ins->c]) {
                ok = false;
                break;
            }
            RE_TRY(slot_set(m, ins->a, cnt + 1));
            pc = ins->d;
            break;
        }
        case OP_REP_SIMPLE: {
            const re_inst *atom = &code[pc + 1];
            uint32_t min = ins->a;
            uint32_t max = ins->b;
            uint32_t q = pos;
            uint32_t count = 0;
            uint32_t np;
            if (ins->f & RF_GREEDY) {
                while (count < max && atom_step(m, atom, q, &np)) {
                    q = np;
                    count++;
                }
                if (count < min) {
                    ok = false;
                    break;
                }
                if (count > min) {
                    RE_TRY(bt_push(m, BT_SIMPLE, pc + 2, q, count, min));
                }
                pos = q;
                pc += 2;
            } else {
                while (count < min) {
                    if (!atom_step(m, atom, q, &np)) {
                        break;
                    }
                    q = np;
                    count++;
                }
                if (count < min) {
                    ok = false;
                    break;
                }
                if (max > min) {
                    RE_TRY(bt_push(m, BT_LAZY, pc + 1, q, count, max));
                }
                pos = q;
                pc += 2;
            }
            break;
        }
        case OP_MATCH:
            return EMBI_RE_MATCH;
        default:
            return EMBI_RE_NO_MATCH;
        }
        if (!ok && !backtrack(m, &pc, &pos)) {
            return EMBI_RE_NO_MATCH;
        }
    }
}

static uint32_t advance_index(const embi_re_input *in, uint32_t s, bool uni)
{
    if (uni && s + 1 < in->len && is_lead(unit_at(in, s)) && is_trail(unit_at(in, s + 1))) {
        return s + 2;
    }
    return s + 1;
}

/* True when the unit at s can begin a match (see build_first_set). s < in->len. */
static bool unit_may_start(const embi_re_prog *prog, const embi_re_input *in, uint32_t s)
{
    uint32_t u = unit_at(in, s);
    return u < 256 ? first_bit(prog->set_bits, u) : prog->set_high;
}

/* Returns the first position at or after s whose unit may begin a match, or in->len when there is
 * none. Steps by code point in u and v mode, so it never stops inside a surrogate pair. */
static uint32_t first_scan(const embi_re_prog *prog, const embi_re_input *in, uint32_t s, bool uni)
{
    if (s >= in->len) {
        return in->len;
    }
    if (prog->set_single != UINT32_MAX && !in->wide) {
        /* One Latin-1 unit: a Latin-1 unit is never a trail surrogate, so any hit is a code point start. */
        const uint8_t *b = in->units;
        const uint8_t *hit = memchr(b + s, (int)prog->set_single, in->len - s);
        return hit ? (uint32_t)(hit - b) : in->len;
    }
    while (s < in->len) {
        if (unit_may_start(prog, in, s)) {
            return s;
        }
        s = advance_index(in, s, uni);
    }
    return in->len;
}

static embi_re_status search_at(const embi_re_prog *prog, embi_re_input in, uint32_t start,
                                uint32_t *caps, const embi_re_limits *limits, bool anchored)
{
    if (start > in.len) {
        return EMBI_RE_NO_MATCH;
    }
    uint32_t local_slots[128];
    bt_entry local_stack[256];
    uint32_t *slots = prog->nslots <= 128 ? local_slots : embi_alloc((size_t)prog->nslots * sizeof *slots);
    matcher m;
    memset(&m, 0, sizeof m);
    m.p = prog;
    m.in = in;
    m.slots = slots;
    m.stack = local_stack;
    m.cap = 256;
    m.heap = false;
    m.max_bytes = (limits && limits->max_bytes) ? limits->max_bytes : RE_DEFAULT_MAX_BYTES;
    m.lim = limits;
    bool uni = (prog->flags & (EMBI_RE_FLAG_U | EMBI_RE_FLAG_V)) != 0;

    embi_re_status st = EMBI_RE_NO_MATCH;
    uint32_t s = start;
    if (uni && s > 0 && s < in.len && is_trail(unit_at(&in, s)) && is_lead(unit_at(&in, s - 1))) {
        s--; /* lastIndex inside a pair maps to the code point containing it */
    }
    for (;;) {
        if (prog->has_set) {
            if (anchored) {
                if (s >= in.len || !unit_may_start(prog, &in, s)) {
                    break;
                }
            } else {
                s = first_scan(prog, &in, s, uni);
                if (s >= in.len) {
                    break;
                }
            }
        }
        for (uint32_t k = 0; k < prog->nslots; k++) {
            slots[k] = EMBI_RE_UNDEF;
        }
        m.sp = 0;
        embi_re_status r = run(&m, 0, s);
        if (r == EMBI_RE_MATCH) {
            for (uint32_t k = 0; k < prog->nslots_cap; k++) {
                caps[k] = slots[k];
            }
            st = EMBI_RE_MATCH;
            break;
        }
        if (r != EMBI_RE_NO_MATCH) {
            st = r;
            break;
        }
        if (anchored || s >= in.len) {
            break;
        }
        s = advance_index(&in, s, uni);
    }
    if (m.heap) {
        embi_free(m.stack, (size_t)m.cap * sizeof(bt_entry));
    }
    if (prog->nslots > 128) {
        embi_free(slots, (size_t)prog->nslots * sizeof *slots);
    }
    return st;
}

embi_re_status embi_re_search(const embi_re_prog *prog, embi_re_input in, uint32_t start,
                              uint32_t *caps, const embi_re_limits *limits)
{
    return search_at(prog, in, start, caps, limits, false);
}

embi_re_status embi_re_match_at(const embi_re_prog *prog, embi_re_input in, uint32_t start,
                                uint32_t *caps, const embi_re_limits *limits)
{
    return search_at(prog, in, start, caps, limits, true);
}
