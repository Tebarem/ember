static bool is_lead(uint32_t c)
{
    return c >= 0xD800u && c <= 0xDBFFu;
}

static bool is_trail(uint32_t c)
{
    return c >= 0xDC00u && c <= 0xDFFFu;
}

static uint32_t cp_from_pair(uint32_t hi, uint32_t lo)
{
    return 0x10000u + ((hi - 0xD800u) << 10) + (lo - 0xDC00u);
}

static bool is_dec(uint32_t c)
{
    return c >= '0' && c <= '9';
}

static bool is_ascii_alpha(uint32_t c)
{
    return (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z');
}

static bool is_syntax_char(uint32_t c)
{
    switch (c) {
    case '^': case '$': case '\\': case '.': case '*': case '+': case '?':
    case '(': case ')': case '[': case ']': case '{': case '}': case '|':
        return true;
    default:
        return false;
    }
}

static int hexval(uint32_t c)
{
    if (c >= '0' && c <= '9') {
        return (int)(c - '0');
    }
    if (c >= 'a' && c <= 'f') {
        return (int)(c - 'a') + 10;
    }
    if (c >= 'A' && c <= 'F') {
        return (int)(c - 'A') + 10;
    }
    return -1;
}

/* ---------- Case mapping and character predicates ---------- */

static uint32_t map_lookup(const embi_re_casemap *map, uint32_t n, uint32_t cp)
{
    uint32_t lo = 0;
    uint32_t hi = n;
    while (lo < hi) {
        uint32_t mid = lo + (hi - lo) / 2;
        if (map[mid].from < cp) {
            lo = mid + 1;
        } else if (map[mid].from > cp) {
            hi = mid;
        } else {
            return map[mid].to;
        }
    }
    return cp;
}

/* Simple case folding (CaseFolding C and S): the Canonicalize of u and v patterns. */
static uint32_t canon_u(uint32_t cp)
{
    if (cp < 128) {
        return (cp >= 'A' && cp <= 'Z') ? cp + 32 : cp;
    }
    return map_lookup(embi_re_fold_u, EMBI_RE_NFOLD_U, cp);
}

/* Canonicalize for non-u patterns: full toUppercase when it is one code unit. */
static uint32_t canon_nu(uint32_t cp)
{
    if (cp < 128) {
        return (cp >= 'a' && cp <= 'z') ? cp - 32 : cp;
    }
    return map_lookup(embi_re_canon_nu, EMBI_RE_NCANON_NU, cp);
}

static uint32_t canon_cp(uint32_t cp, bool uni)
{
    return uni ? canon_u(cp) : canon_nu(cp);
}

static bool is_word_basic(uint32_t c)
{
    return (c >= '0' && c <= '9') || (c >= 'A' && c <= 'Z') || (c >= 'a' && c <= 'z') || c == '_';
}

/* WordCharacters: the basic set, plus under u+i or v+i the characters whose simple case fold is a
 * basic word character (U+017F and U+212A). */
static bool is_word_ch(uint32_t c, bool extended)
{
    return is_word_basic(c) || (extended && (c == 0x17F || c == 0x212A));
}

/* ---------- Set algebra (arena-backed) ---------- */

/* Empties a set for refilling. A shared set's storage belongs to everyone, so it is dropped. */
static void set_reset(re_set *s)
{
    if (s->shared) {
        s->r = nullptr;
        s->cap = 0;
        s->shared = false;
    }
    s->n = 0;
}

/* Room for 'extra' more ranges; grows geometrically. */
static void set_reserve(embi_arena *ar, re_set *s, uint32_t extra)
{
    if (extra > s->cap - s->n) {
        uint32_t nc = s->cap ? s->cap * 2 : 8;
        while (nc - s->n < extra) {
            nc *= 2;
        }
        re_range *nr = embi_arena_alloc(ar, (size_t)nc * sizeof *nr, alignof(re_range));
        if (s->n) {
            memcpy(nr, s->r, (size_t)s->n * sizeof *nr);
        }
        s->r = nr;
        s->cap = nc;
        s->shared = false;
    }
}

static void set_push(embi_arena *ar, re_set *s, uint32_t lo, uint32_t hi)
{
    set_reserve(ar, s, 1);
    s->r[s->n].lo = lo;
    s->r[s->n].hi = hi;
    s->n++;
}

static int range_cmp(const void *a, const void *b)
{
    const re_range *x = a;
    const re_range *y = b;
    return (x->lo > y->lo) - (x->lo < y->lo);
}

/* Sorts and merges, so the set is canonical. A set that already is canonical is left untouched
 * (shared sets are never written). */
static void set_norm(re_set *s)
{
    bool canon = true;
    for (uint32_t i = 1; i < s->n; i++) {
        if (s->r[i].lo <= s->r[i - 1].hi + 1) {
            canon = false;
            break;
        }
    }
    if (!canon) {
        SDL_qsort(s->r, s->n, sizeof *s->r, range_cmp);
        uint32_t k = 0;
        for (uint32_t i = 0; i < s->n; i++) {
            if (k > 0 && s->r[i].lo <= s->r[k - 1].hi + 1) {
                if (s->r[i].hi > s->r[k - 1].hi) {
                    s->r[k - 1].hi = s->r[i].hi;
                }
            } else {
                s->r[k++] = s->r[i];
            }
        }
        s->n = k;
    }
    s->nnorm = s->n;
}

/* Keeps an accumulator near the size of its union while many sets are added to it, so a class of
 * N property escapes never holds N copies of the ranges. Amortized O(1) per range added. */
static void set_maybe_norm(re_set *s)
{
    if (s->n > 2 * s->nnorm + 1024) {
        set_norm(s);
    }
}

static bool set_has(const re_set *s, uint32_t c)
{
    uint32_t lo = 0;
    uint32_t hi = s->n;
    while (lo < hi) {
        uint32_t mid = lo + (hi - lo) / 2;
        if (c < s->r[mid].lo) {
            hi = mid;
        } else if (c > s->r[mid].hi) {
            lo = mid + 1;
        } else {
            return true;
        }
    }
    return false;
}

static void set_add_all(embi_arena *ar, re_set *dst, const re_set *src)
{
    if (src->n) {
        set_reserve(ar, dst, src->n);
        memcpy(dst->r + dst->n, src->r, (size_t)src->n * sizeof *src->r);
        dst->n += src->n;
    }
}

static void set_union(embi_arena *ar, const re_set *a, const re_set *b, re_set *out)
{
    set_reset(out);
    set_add_all(ar, out, a);
    set_add_all(ar, out, b);
    set_norm(out);
}

static void set_intersect(embi_arena *ar, const re_set *a, const re_set *b, re_set *out)
{
    set_reset(out);
    uint32_t i = 0;
    uint32_t j = 0;
    while (i < a->n && j < b->n) {
        uint32_t lo = a->r[i].lo > b->r[j].lo ? a->r[i].lo : b->r[j].lo;
        uint32_t hi = a->r[i].hi < b->r[j].hi ? a->r[i].hi : b->r[j].hi;
        if (lo <= hi) {
            set_push(ar, out, lo, hi);
        }
        if (a->r[i].hi < b->r[j].hi) {
            i++;
        } else {
            j++;
        }
    }
}

/* out = a minus b; both inputs canonical. */
static void set_subtract(embi_arena *ar, const re_set *a, const re_set *b, re_set *out)
{
    set_reset(out);
    uint32_t j = 0;
    for (uint32_t i = 0; i < a->n; i++) {
        uint32_t lo = a->r[i].lo;
        uint32_t hi = a->r[i].hi;
        bool done = false;
        while (j < b->n && b->r[j].hi < lo) {
            j++;
        }
        for (uint32_t k = j; k < b->n && b->r[k].lo <= hi; k++) {
            if (b->r[k].lo > lo) {
                set_push(ar, out, lo, b->r[k].lo - 1);
            }
            if (b->r[k].hi >= hi) {
                done = true;
                break;
            }
            lo = b->r[k].hi + 1;
        }
        if (!done) {
            set_push(ar, out, lo, hi);
        }
    }
}

/* Decodes one set from the generated tables (varint count, then gap and length per range). */
static uint32_t dec_varint(const uint8_t **p)
{
    uint32_t v = 0;
    uint32_t shift = 0;
    uint8_t b;
    do {
        b = *(*p)++;
        v |= (uint32_t)(b & 0x7F) << shift;
        shift += 7;
    } while ((b & 0x80) != 0 && shift < 35);
    return v;
}

/* Appends the ranges of one table set to 'out' (not normalized). */
static void set_from_prop_id(embi_arena *ar, const uint8_t *data, uint32_t id, re_set *out)
{
    const uint8_t *d = data + embi_re_set_off[id];
    uint32_t count = dec_varint(&d);
    set_reserve(ar, out, count);
    uint32_t prev = 0;
    for (uint32_t i = 0; i < count; i++) {
        uint32_t lo = prev + dec_varint(&d);
        uint32_t hi = lo + dec_varint(&d);
        set_push(ar, out, lo, hi);
        prev = hi + 1;
    }
}

/* Looks up a property name in one namespace. */
static const embi_re_pname *prop_find(const char *name, int ns)
{
    for (uint32_t i = 0; i < EMBI_RE_NPNAMES; i++) {
        const embi_re_pname *e = &embi_re_pnames[i];
        if (e->ns == ns && strcmp(e->name, name) == 0) {
            return e;
        }
    }
    return nullptr;
}

/* The union of a property's member sets, normalized, into 'out' (appended to nothing: out starts
 * empty). Decodes straight into 'out'; no per-member temporaries. */
static void prop_build(re_parser *p, const embi_re_pname *e, re_set *out)
{
#ifdef EMBER_LZ_ASSETS
    /* Expanded on the first property of a compile (18 KB to 45 KB) and freed when the compile ends. */
    if (p->setdata == nullptr) {
        p->setdata = embi_lz_unpack(embi_lz_tables_re_set_data, sizeof embi_lz_tables_re_set_data, &p->setdata_raw);
        if (p->setdata == nullptr) {
            set_norm(out); /* out of memory: an empty set */
            return;
        }
    }
    const uint8_t *data = p->setdata;
#else
    const uint8_t *data = embi_re_set_data;
#endif
    for (uint32_t m = 0; m < e->n; m++) {
        set_from_prop_id(&p->tmp, data, embi_re_pmembers[e->first + m], out);
    }
    set_norm(out);
}

/* Every code point the pattern can match in this mode. v+i excludes characters that do not fold
 * to themselves (AllCharacters), so complements stay closed under case folding. */
static void fold_domain(embi_arena *ar, re_set *out)
{
    set_reset(out);
    set_reserve(ar, out, EMBI_RE_NFOLD_U);
    for (uint32_t i = 0; i < EMBI_RE_NFOLD_U; i++) {
        set_push(ar, out, embi_re_fold_u[i].from, embi_re_fold_u[i].from);
    }
    set_norm(out);
}

/* ---------- Parser helpers ---------- */

static void perr(re_parser *p, const char *msg)
{
    if (p->failed) {
        return;
    }
    p->failed = true;
    if (p->err) {
        p->err->pos = p->pos;
        p->err->msg = msg;
    }
}

static uint32_t cur(const re_parser *p)
{
    return p->pos < p->len ? p->src[p->pos] : RE_NONE;
}

static uint32_t peek(const re_parser *p, uint32_t k)
{
    return p->pos + k < p->len ? p->src[p->pos + k] : RE_NONE;
}

static bool at(const re_parser *p, uint32_t c)
{
    return p->pos < p->len && p->src[p->pos] == c;
}

static bool at2(const re_parser *p, uint32_t c)
{
    return p->pos + 1 < p->len && p->src[p->pos] == c && p->src[p->pos + 1] == c;
}

static re_node *node_new(re_parser *p, uint8_t type)
{
    re_node *n = embi_arena_alloc(p->ar, sizeof *n, alignof(re_node));
    memset(n, 0, sizeof *n);
    n->type = type;
    return n;
}

static uint32_t *u32_array(embi_arena *ar, uint32_t n)
{
    return embi_arena_alloc(ar, (size_t)(n ? n : 1) * sizeof(uint32_t), alignof(uint32_t));
}

/* Reads one code point (a surrogate pair counts as one in u and v mode). */
static uint32_t read_cp(re_parser *p, bool uni)
{
    uint32_t c = p->src[p->pos++];
    if (uni && is_lead(c) && p->pos < p->len && is_trail(p->src[p->pos])) {
        c = cp_from_pair(c, p->src[p->pos]);
        p->pos++;
    }
    return c;
}

/* Reads a decimal number, saturating. Returns false if there are no digits. */
static bool read_decimal(re_parser *p, uint32_t *out)
{
    if (!is_dec(cur(p))) {
        return false;
    }
    uint64_t v = 0;
    while (is_dec(cur(p))) {
        v = v * 10 + (cur(p) - '0');
        if (v > 0xFFFFFFFEu) {
            v = 0xFFFFFFFEu;
        }
        p->pos++;
    }
    *out = (uint32_t)v;
    return true;
}

/* Four hex digits starting 'off' code units after the current position. */
static bool hex4_at(const re_parser *p, uint32_t off, uint32_t *out)
{
    uint32_t v = 0;
    for (uint32_t k = 0; k < 4; k++) {
        uint32_t idx = p->pos + off + k;
        if (idx >= p->len) {
            return false;
        }
        int h = hexval(p->src[idx]);
        if (h < 0) {
            return false;
        }
        v = v * 16 + (uint32_t)h;
    }
    *out = v;
    return true;
}

/* The body of a \u escape, with pos just after the 'u'. Braces are allowed in u and v mode and in
 * group names; surrogate pairs (𝐀) combine. */
static bool parse_u_body(re_parser *p, uint32_t *out)
{
    if (at(p, '{')) {
        p->pos++;
        uint32_t v = 0;
        uint32_t nd = 0;
        int h;
        while (p->pos < p->len && (h = hexval(p->src[p->pos])) >= 0) {
            v = v * 16 + (uint32_t)h;
            nd++;
            p->pos++;
            if (v > 0x10FFFFu) {
                perr(p, "invalid unicode escape");
                return false;
            }
        }
        if (nd == 0 || !at(p, '}')) {
            perr(p, "invalid unicode escape");
            return false;
        }
        p->pos++;
        *out = v;
        return true;
    }
    uint32_t v;
    if (!hex4_at(p, 0, &v)) {
        perr(p, "invalid unicode escape");
        return false;
    }
    p->pos += 4;
    if (is_lead(v) && at(p, '\\') && peek(p, 1) == 'u') {
        uint32_t t;
        if (hex4_at(p, 2, &t) && is_trail(t)) {
            v = cp_from_pair(v, t);
            p->pos += 6;
        }
    }
    *out = v;
    return true;
}

/* Legacy octal (Annex B): one to three digits, at most 0377. pos is at the first digit. */
static uint32_t legacy_octal(re_parser *p)
{
    uint32_t d1 = cur(p) - '0';
    p->pos++;
    uint32_t v = d1;
    if (cur(p) >= '0' && cur(p) <= '7') {
        v = v * 8 + (cur(p) - '0');
        p->pos++;
        if (d1 <= 3 && cur(p) >= '0' && cur(p) <= '7') {
            v = v * 8 + (cur(p) - '0');
            p->pos++;
        }
    }
    return v;
}

/* CharacterEscape. pos is at the character after the backslash. in_class admits the class-only
 * forms (\c with a digit or underscore, and octal rules). */
static bool parse_char_escape(re_parser *p, bool in_class, uint32_t *out)
{
    uint32_t c = cur(p);
    switch (c) {
    case 'f':
        p->pos++;
        *out = 0x0C;
        return true;
    case 'n':
        p->pos++;
        *out = 0x0A;
        return true;
    case 'r':
        p->pos++;
        *out = 0x0D;
        return true;
    case 't':
        p->pos++;
        *out = 0x09;
        return true;
    case 'v':
        p->pos++;
        *out = 0x0B;
        return true;
    case 'c': {
        uint32_t d = peek(p, 1);
        if (is_ascii_alpha(d) || (in_class && !p->uni && (is_dec(d) || d == '_'))) {
            *out = d % 32;
            p->pos += 2;
            return true;
        }
        if (p->uni) {
            perr(p, "invalid unicode escape");
            return false;
        }
        /* Annex B: the backslash is a literal; the 'c' is read as an ordinary character next. */
        *out = '\\';
        return true;
    }
    case '0': case '1': case '2': case '3': case '4': case '5': case '6': case '7':
        if (p->uni) {
            if (c == '0' && !is_dec(peek(p, 1))) {
                p->pos++;
                *out = 0;
                return true;
            }
            perr(p, "invalid escape");
            return false;
        }
        *out = legacy_octal(p);
        return true;
    case '8':
    case '9':
        if (p->uni) {
            perr(p, "invalid escape");
            return false;
        }
        p->pos++;
        *out = c;
        return true;
    case 'x': {
        int h1 = hexval(peek(p, 1));
        int h2 = hexval(peek(p, 2));
        if (h1 >= 0 && h2 >= 0) {
            *out = (uint32_t)(h1 * 16 + h2);
            p->pos += 3;
            return true;
        }
        if (p->uni) {
            perr(p, "invalid escape");
            return false;
        }
        p->pos++;
        *out = 'x';
        return true;
    }
    case 'u': {
        p->pos++;
        if (p->uni) {
            return parse_u_body(p, out);
        }
        uint32_t v;
        if (hex4_at(p, 0, &v)) {
            p->pos += 4;
            *out = v;
            return true;
        }
        *out = 'u';
        return true;
    }
    default:
        if (p->uni) {
            if (is_syntax_char(c) || c == '/') {
                p->pos++;
                *out = c;
                return true;
            }
            perr(p, "invalid escape");
            return false;
        }
        p->pos++;
        *out = c;
        return true;
    }
}

